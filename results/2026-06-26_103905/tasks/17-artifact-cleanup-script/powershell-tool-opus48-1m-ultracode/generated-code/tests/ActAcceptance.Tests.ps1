#Requires -Modules @{ ModuleName = 'Pester'; ModuleVersion = '5.0.0' }

<#
    End-to-end ACCEPTANCE tests: every test case is driven THROUGH the GitHub
    Actions workflow via `act` (nektos/act) in Docker — the script is never
    exercised directly here.

    For each case the harness:
      1. builds an isolated temp git repo with the project files + that case's
         fixture data (written to fixtures/artifacts.json),
      2. runs `act push --rm`, capturing all output,
      3. appends the output to act-result.txt (clearly delimited),
      4. asserts act exited 0, every job shows "Job succeeded", and the printed
         summary matches the EXACT known-good values for that fixture.

    Budget note: act is slow (~30-90s/run), so this runs act exactly ONCE per
    case (3 total) and fail-fast aborts the remaining act runs if the first
    case's workflow is fundamentally broken — conserving the run budget.

    Tagged 'Acceptance' so it is excluded from the hermetic in-container unit
    run. Execute on the host with:
        Invoke-Pester -Path tests/ActAcceptance.Tests.ps1

    Helper functions live in AcceptanceHelpers.ps1 and are dot-sourced in both
    Pester phases (top level for discovery, BeforeAll for the run phase).
#>

. (Join-Path $PSScriptRoot 'AcceptanceHelpers.ps1')

BeforeDiscovery {
    $cases = Get-AcceptanceCases
}

Describe 'Artifact cleanup workflow via act' -Tag 'Acceptance' {

    BeforeAll {
        . (Join-Path $PSScriptRoot 'AcceptanceHelpers.ps1')

        $script:Root       = Split-Path $PSScriptRoot -Parent
        $script:ResultFile = Join-Path $script:Root 'act-result.txt'

        # Start a fresh act-result.txt for this run.
        Set-Content -LiteralPath $script:ResultFile -Encoding utf8 -Value @(
            '################################################################',
            '# act-result.txt - Artifact Cleanup workflow acceptance output',
            '# Generated by tests/ActAcceptance.Tests.ps1',
            '################################################################'
        )

        # Run each case through act once, recording output + exit code. Abort the
        # remaining (expensive) act runs if a case's workflow fails outright.
        $script:ActOutputs = @{}
        $failedHard = $false
        foreach ($case in Get-AcceptanceCases) {
            if ($failedHard) {
                Add-Content -LiteralPath $script:ResultFile -Value @(
                    '', "===== CASE $($case.Name): SKIPPED (earlier case failed; conserving act-run budget) ====="
                )
                continue
            }

            $res = Invoke-ActCase -Root $script:Root -Case $case
            $script:ActOutputs[$case.Name] = $res

            Add-Content -LiteralPath $script:ResultFile -Value @(
                '',
                '================================================================',
                "===== CASE: $($case.Name) =====",
                "===== act exit code: $($res.Exit) =====",
                '================================================================',
                $res.Output
            )

            if ($res.Exit -ne 0) { $failedHard = $true }
        }
    }

    Context 'Case <Name>' -ForEach $cases {

        BeforeAll {
            $script:Result = $script:ActOutputs[$Name]
        }

        It 'produced act output (the case actually ran)' {
            $script:Result | Should -Not -BeNullOrEmpty -Because 'a prior case may have aborted the run'
        }

        It 'act exited with code 0' {
            $script:Result.Exit | Should -Be 0 -Because ($script:Result.Output)
        }

        It 'every job reports "Job succeeded"' {
            ([regex]::Matches($script:Result.Output, 'Job succeeded')).Count |
                Should -BeGreaterOrEqual 2
            $script:Result.Output | Should -Not -Match 'Job failed'
        }

        It 'ran the Pester unit suite inside the container' {
            $script:Result.Output | Should -Match 'All unit tests passed'
        }

        It 'printed the cleanup plan summary' {
            $script:Result.Output | Should -Match 'ARTIFACT CLEANUP PLAN'
        }

        It 'summary value <_> matches the known-good result' -ForEach @(
            'TotalArtifacts', 'DeletedCount', 'RetainedCount',
            'SpaceReclaimedBytes', 'RetainedSizeBytes', 'TotalSizeBytes'
        ) {
            $key = $_
            $actual = Get-SummaryValue -Output $script:Result.Output -Key $key
            $actual | Should -Be $Expected[$key] -Because "summary line '$key'"
        }

        It 'emitted the expected deletion line with the correct reason' {
            $script:Result.Output | Should -Match $ExpectDelete
        }
    }
}
