#!/usr/bin/env pwsh
#Requires -Version 7.0
<#
.SYNOPSIS
    End-to-end test harness: runs the Dependency License Checker workflow through
    `act` (a local GitHub Actions runner) for several fixture cases and asserts
    on EXACT expected output.

.DESCRIPTION
    For each test case this harness:
      1. Builds an isolated temp git repo containing the project files plus that
         case's fixture data (manifest + mock license database).
      2. Runs `act push --rm` against the workflow and captures all output.
      3. Appends the output to ./act-result.txt (delimited per case).
      4. Asserts act exited 0, that every job reports "Job succeeded", and that
         the captured output contains the exact known-good report values for that
         case's input.

    Run from anywhere:  pwsh -File ./Run-ActTests.ps1
#>

[CmdletBinding()]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$ProjectDir = $PSScriptRoot
$ActResult  = Join-Path $ProjectDir 'act-result.txt'
$Workflow   = '.github/workflows/dependency-license-checker.yml'

# Start each run with a fresh result artifact.
Set-Content -Path $ActResult -Value "ACT RESULT LOG - generated by Run-ActTests.ps1`n"

# Project files copied verbatim into every case's temp repo (fixtures/ is built
# fresh per case so the manifest type is fully controlled).
$CopyItems = @('Invoke-LicenseCheck.ps1', 'src', 'config', 'tests', '.github', '.actrc')

# ---------------------------------------------------------------------------
# Test cases. Each declares its fixture files and the EXACT strings that must
# appear in the act output for that input.
# ---------------------------------------------------------------------------
$Cases = @(
    @{
        Name  = 'package-json-mixed (approved + denied + unknown)'
        Files = @{
            'fixtures/package.json' = @'
{
  "name": "mixed-app",
  "version": "1.0.0",
  "dependencies": {
    "express": "4.18.2",
    "lodash": "4.17.21",
    "copyleft-lib": "3.0.0",
    "mystery-pkg": "2.0.0"
  }
}
'@
            'fixtures/license-db.json' = @'
{ "express": "MIT", "lodash": "MIT", "copyleft-lib": "GPL-3.0" }
'@
        }
        Expect = @(
            '[APPROVED] express@4.18.2 -> MIT'
            '[APPROVED] lodash@4.17.21 -> MIT'
            '[DENIED] copyleft-lib@3.0.0 -> GPL-3.0'
            '[UNKNOWN] mystery-pkg@2.0.0 -> UNKNOWN'
            'SUMMARY: total=4 approved=2 denied=1 unknown=1'
            'RESULT: NON-COMPLIANT'
        )
    }
    @{
        Name  = 'requirements-txt-compliant (all approved)'
        Files = @{
            'fixtures/requirements.txt' = @'
# project python deps
requests==2.31.0
flask>=2.0.0
'@
            'fixtures/license-db.json' = @'
{ "requests": "Apache-2.0", "flask": "BSD-3-Clause" }
'@
        }
        Expect = @(
            '[APPROVED] requests@==2.31.0 -> Apache-2.0'
            '[APPROVED] flask@>=2.0.0 -> BSD-3-Clause'
            'SUMMARY: total=2 approved=2 denied=0 unknown=0'
            'RESULT: COMPLIANT'
        )
    }
    @{
        Name  = 'package-json-unknowns (approved + two unknown)'
        Files = @{
            'fixtures/package.json' = @'
{
  "name": "unknown-app",
  "version": "1.0.0",
  "dependencies": {
    "lodash": "4.17.21",
    "exotic-pkg": "1.0.0",
    "ghost-pkg": "1.0.0"
  }
}
'@
            'fixtures/license-db.json' = @'
{ "lodash": "MIT", "exotic-pkg": "WTFPL" }
'@
        }
        Expect = @(
            '[APPROVED] lodash@4.17.21 -> MIT'
            '[UNKNOWN] exotic-pkg@1.0.0 -> WTFPL'
            '[UNKNOWN] ghost-pkg@1.0.0 -> UNKNOWN'
            'SUMMARY: total=3 approved=1 denied=0 unknown=2'
            'RESULT: COMPLIANT'
        )
    }
)

function New-CaseRepo {
    param([hashtable]$Files)

    $tmp = Join-Path ([System.IO.Path]::GetTempPath()) ("lic-act-" + [guid]::NewGuid().ToString('N'))
    New-Item -ItemType Directory -Path $tmp | Out-Null

    foreach ($item in $CopyItems) {
        $src = Join-Path $ProjectDir $item
        if (Test-Path -LiteralPath $src) {
            Copy-Item -LiteralPath $src -Destination (Join-Path $tmp $item) -Recurse -Force
        }
    }

    # Build the case-specific fixtures fresh.
    New-Item -ItemType Directory -Path (Join-Path $tmp 'fixtures') -Force | Out-Null
    foreach ($rel in $Files.Keys) {
        $dest = Join-Path $tmp $rel
        New-Item -ItemType Directory -Path (Split-Path $dest -Parent) -Force | Out-Null
        Set-Content -Path $dest -Value $Files[$rel] -NoNewline
    }

    # act requires a git repo with at least one commit.
    git -C $tmp init -q
    git -C $tmp add -A
    git -C $tmp -c user.email='ci@example.com' -c user.name='CI' commit -q -m 'fixture' | Out-Null

    return $tmp
}

$failures = 0
$caseNumber = 0

foreach ($case in $Cases) {
    $caseNumber++
    Write-Host "`n=== CASE $caseNumber/$($Cases.Count): $($case.Name) ===" -ForegroundColor Cyan

    $repo = New-CaseRepo -Files $case.Files

    try {
        Push-Location $repo
        # --pull=false keeps act offline-friendly (the runner image is local).
        $output = & act push --rm --pull=false -W $Workflow 2>&1 | Out-String
        $actExit = $LASTEXITCODE
    }
    finally {
        Pop-Location
    }

    # 2 + 3: persist all output to the required artifact, clearly delimited.
    $delim = "`n" + ('=' * 78) + "`nTEST CASE ${caseNumber}: $($case.Name)`n" + `
             "act exit code: $actExit`n" + ('=' * 78) + "`n"
    Add-Content -Path $ActResult -Value $delim
    Add-Content -Path $ActResult -Value $output

    # --- Assertions -------------------------------------------------------
    $caseFailed = $false

    # (a) act must succeed.
    if ($actExit -ne 0) {
        Write-Host "  FAIL: act exit code was $actExit (expected 0)" -ForegroundColor Red
        $caseFailed = $true
    } else {
        Write-Host "  PASS: act exit code 0" -ForegroundColor Green
    }

    # (b) every job must report success. The workflow has two jobs.
    $jobSucceeded = ([regex]::Matches($output, 'Job succeeded')).Count
    if ($jobSucceeded -lt 2) {
        Write-Host "  FAIL: expected >=2 'Job succeeded' markers, found $jobSucceeded" -ForegroundColor Red
        $caseFailed = $true
    } else {
        Write-Host "  PASS: found $jobSucceeded 'Job succeeded' markers" -ForegroundColor Green
    }

    # (c) exact expected report values must be present.
    foreach ($expected in $case.Expect) {
        if ($output.Contains($expected)) {
            Write-Host "  PASS: output contains '$expected'" -ForegroundColor Green
        } else {
            Write-Host "  FAIL: output MISSING '$expected'" -ForegroundColor Red
            $caseFailed = $true
        }
    }

    if ($caseFailed) { $failures++ }

    Remove-Item -LiteralPath $repo -Recurse -Force -ErrorAction SilentlyContinue
}

Write-Host "`n================ SUMMARY ================" -ForegroundColor Cyan
Write-Host "Cases run : $($Cases.Count)"
Write-Host "Failures  : $failures"
Write-Host "Artifact  : $ActResult"

if ($failures -gt 0) {
    Write-Host "RESULT: FAILED" -ForegroundColor Red
    exit 1
}
Write-Host "RESULT: ALL CASES PASSED" -ForegroundColor Green
exit 0
