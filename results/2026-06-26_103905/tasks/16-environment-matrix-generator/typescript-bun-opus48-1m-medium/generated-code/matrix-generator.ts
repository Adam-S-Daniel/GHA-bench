// Environment build matrix generator for GitHub Actions `strategy.matrix`.
//
// Given a config describing OS options, language versions, and feature flags,
// this module expands the cartesian product of those axes, applies
// include/exclude rules using GitHub's documented semantics, enforces a
// maximum matrix size, and emits the full matrix as JSON.

/** A single value an axis entry can take. */
export type AxisValue = string | number | boolean;

/** A fully-resolved job combination: an object of axis -> value. */
export type Combination = Record<string, AxisValue>;

/** The named axes (os, node, flags, ...), each a list of allowed values. */
export type Axes = Record<string, AxisValue[]>;

/** Compute the cartesian product of all axes in row-major (last axis varies fastest) order.
 *
 * Mirrors GitHub Actions: combinations are generated by iterating the axes in
 * declaration order. An empty axis collapses the whole product to zero rows.
 */
export function cartesianProduct(axes: Axes): Combination[] {
  // Start with a single empty combination and fold each axis into it.
  let combos: Combination[] = [{}];
  for (const [key, values] of Object.entries(axes)) {
    const next: Combination[] = [];
    for (const combo of combos) {
      for (const value of values) {
        next.push({ ...combo, [key]: value });
      }
    }
    combos = next;
  }
  return combos;
}

/** Full generator config supplied by the user (typically parsed from JSON). */
export interface MatrixConfig {
  /** The matrix axes: os, language versions, feature flags, etc. */
  matrix: Axes;
  /** Combinations to add/extend, following GitHub `include` semantics. */
  include?: Combination[];
  /** Combinations to remove if they match all listed key/value pairs. */
  exclude?: Combination[];
  /** Maximum number of concurrent jobs (GitHub `max-parallel`). */
  maxParallel?: number;
  /** Whether to cancel in-progress jobs when one fails (GitHub `fail-fast`). */
  failFast?: boolean;
  /** Hard cap on the number of generated combinations; exceeding it is an error. */
  maxSize?: number;
}

/** Error thrown when the generated matrix exceeds the configured `maxSize`. */
export class MatrixSizeError extends Error {
  constructor(
    public readonly size: number,
    public readonly maxSize: number,
  ) {
    super(
      `Generated matrix has ${size} combinations, which exceeds the maximum of ${maxSize}`,
    );
    this.name = "MatrixSizeError";
  }
}

/** True if `combo` contains every key/value pair found in `filter`. */
function matches(combo: Combination, filter: Combination): boolean {
  return Object.entries(filter).every(([key, value]) => combo[key] === value);
}

/** Remove any combination that matches all key/value pairs of an exclude entry.
 *
 * An exclude entry may be partial: `{ os: "windows" }` drops every windows row.
 */
export function applyExclude(
  combos: Combination[],
  exclude: Combination[],
): Combination[] {
  if (exclude.length === 0) return combos;
  return combos.filter(
    (combo) => !exclude.some((entry) => matches(combo, entry)),
  );
}

/** Apply GitHub Actions `include` semantics.
 *
 * For each include object: if its key/value pairs can be added to an existing
 * combination WITHOUT overwriting any of that combination's original axis
 * values, the extra fields are merged into every compatible combination.
 * Otherwise the include object becomes a brand-new combination of its own.
 *
 * "Original axis values" are the keys produced by the cartesian product; an
 * include may freely overwrite a value that a previous include added.
 */
export function applyInclude(
  combos: Combination[],
  include: Combination[],
  originalKeys: Set<string>,
): Combination[] {
  // `base` holds the original cartesian rows (mutated as includes extend them).
  // Only these rows are candidates for extension; rows created by an include
  // are collected in `extras` and never extended by later includes — this is
  // the subtle part of GitHub's algorithm.
  const base = combos.map((c) => ({ ...c }));
  const extras: Combination[] = [];

  for (const entry of include) {
    let added = false;
    for (const combo of base) {
      // The include is incompatible if it tries to change an original axis
      // value to something different than the combination already has.
      const conflicts = Object.entries(entry).some(
        ([key, value]) =>
          originalKeys.has(key) && key in combo && combo[key] !== value,
      );
      if (conflicts) continue;
      // Compatible: merge the extra fields in (added fields may be overwritten).
      Object.assign(combo, entry);
      added = true;
    }
    if (!added) {
      // Could not extend any original combination -> new standalone row.
      extras.push({ ...entry });
    }
  }
  return [...base, ...extras];
}

/** The generated matrix, shaped for direct use in a workflow. */
export interface GeneratedMatrix {
  failFast: boolean;
  maxParallel: number | null;
  size: number;
  include: Combination[];
}

export function generateMatrix(config: MatrixConfig): GeneratedMatrix {
  // --- Validate the config up front with meaningful errors. ---
  if (config === null || typeof config !== "object") {
    throw new Error("Config must be an object");
  }
  if (config.matrix === undefined || config.matrix === null) {
    throw new Error("Config must include a `matrix` object describing the axes");
  }
  if (typeof config.matrix !== "object" || Array.isArray(config.matrix)) {
    throw new Error("`matrix` must be an object mapping axis names to value arrays");
  }
  for (const [axis, values] of Object.entries(config.matrix)) {
    if (!Array.isArray(values)) {
      throw new Error(`Axis \`${axis}\` must be an array of values`);
    }
  }
  if (config.include !== undefined && !Array.isArray(config.include)) {
    throw new Error("`include` must be an array of objects");
  }
  if (config.exclude !== undefined && !Array.isArray(config.exclude)) {
    throw new Error("`exclude` must be an array of objects");
  }

  const originalKeys = new Set(Object.keys(config.matrix));

  // --- Expand, then exclude, then include (GitHub's documented order). ---
  let combos = cartesianProduct(config.matrix);
  combos = applyExclude(combos, config.exclude ?? []);
  combos = applyInclude(combos, config.include ?? [], originalKeys);

  // --- Enforce the maximum matrix size. ---
  if (config.maxSize !== undefined && combos.length > config.maxSize) {
    throw new MatrixSizeError(combos.length, config.maxSize);
  }

  return {
    failFast: config.failFast ?? true,
    maxParallel: config.maxParallel ?? null,
    size: combos.length,
    include: combos,
  };
}

// ---------------------------------------------------------------------------
// Command-line interface.
//
// Usage:
//   bun run matrix-generator.ts <config.json>   # read from a file
//   bun run matrix-generator.ts -               # read JSON config from stdin
//
// Prints the generated matrix as pretty JSON on stdout. On any error, prints a
// meaningful message to stderr and exits with code 1.
// ---------------------------------------------------------------------------

const USAGE =
  "Usage: bun run matrix-generator.ts <config.json | ->\n" +
  "  Reads a JSON matrix config and prints the generated GitHub Actions matrix.";

export async function main(argv: string[]): Promise<number> {
  const arg = argv[0];
  if (!arg) {
    process.stderr.write(USAGE + "\n");
    return 1;
  }

  // 1. Load the raw config text from stdin ('-') or the given file path.
  let raw: string;
  try {
    raw =
      arg === "-"
        ? await Bun.stdin.text()
        : await Bun.file(arg).text();
  } catch (err) {
    process.stderr.write(
      `Failed to read config from "${arg}": ${(err as Error).message}\n`,
    );
    return 1;
  }

  // 2. Parse JSON with a clear error if it is malformed.
  let config: MatrixConfig;
  try {
    config = JSON.parse(raw) as MatrixConfig;
  } catch (err) {
    process.stderr.write(
      `Invalid JSON in config "${arg}": ${(err as Error).message}\n`,
    );
    return 1;
  }

  // 3. Generate and print the matrix; surface validation/size errors clearly.
  try {
    const matrix = generateMatrix(config);
    process.stdout.write(JSON.stringify(matrix, null, 2) + "\n");
    return 0;
  } catch (err) {
    process.stderr.write(`Error: ${(err as Error).message}\n`);
    return 1;
  }
}

// Only run the CLI when executed directly (not when imported by tests).
if (import.meta.main) {
  main(process.argv.slice(2)).then((code) => process.exit(code));
}
