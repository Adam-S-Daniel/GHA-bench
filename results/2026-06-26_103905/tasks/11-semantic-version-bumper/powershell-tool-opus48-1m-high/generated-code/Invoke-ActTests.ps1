<#
.SYNOPSIS
    Integration test harness: runs the semantic-version-bumper workflow end to
    end through `act` (nektos/act) for several fixture scenarios and asserts on
    the EXACT version produced.

.DESCRIPTION
    For each test case this harness:
      1. Builds an isolated temp git repo containing the project files, the
         workflow, .actrc, and that case's fixture data (version file +
         commits.txt).
      2. Runs `act push --rm` inside it.
      3. Appends the full, clearly-delimited act output to act-result.txt.
      4. Asserts act exited 0, that BOTH jobs report "Job succeeded", and that
         the output contains the exact expected NEW_VERSION / BUMP_TYPE /
         REPORT_VERSION values.

    Run from the project directory:  pwsh ./Invoke-ActTests.ps1
    Exit code is 0 only if every assertion passes.
#>
[CmdletBinding()]
param(
    [string] $ResultFile = (Join-Path $PSScriptRoot 'act-result.txt')
)

$ErrorActionPreference = 'Stop'
$Root = $PSScriptRoot

# Files every test repo needs (the script library, CLI, unit tests, workflow).
$ProjectFiles = @(
    'SemanticVersionBumper.ps1',
    'Invoke-Bump.ps1',
    'SemanticVersionBumper.Tests.ps1'
)

# Test matrix: each case pins an exact expected result so we assert real
# values, not just "a version appeared".
$Cases = @(
    [pscustomobject]@{
        Name            = 'feat-minor'
        VersionFileName = 'version.txt'
        VersionContent  = "1.1.0`n"
        CommitFixture   = 'fixtures/commits-feat.txt'
        ExpectedVersion = '1.2.0'
        ExpectedType    = 'minor'
    },
    [pscustomobject]@{
        Name            = 'fix-patch'
        VersionFileName = 'version.txt'
        VersionContent  = "1.1.0`n"
        CommitFixture   = 'fixtures/commits-fix.txt'
        ExpectedVersion = '1.1.1'
        ExpectedType    = 'patch'
    },
    [pscustomobject]@{
        Name            = 'breaking-major'
        VersionFileName = 'package.json'
        VersionContent  = "{ `"name`": `"demo`", `"version`": `"2.3.4`" }`n"
        CommitFixture   = 'fixtures/commits-breaking.txt'
        ExpectedVersion = '3.0.0'
        ExpectedType    = 'major'
    }
)

# Start a fresh result artifact.
Set-Content -LiteralPath $ResultFile -Value "act integration results - generated by Invoke-ActTests.ps1`n"

$failures = New-Object System.Collections.Generic.List[string]

function Add-Result {
    param([string] $Text)
    Add-Content -LiteralPath $ResultFile -Value $Text
}

foreach ($case in $Cases) {
    Write-Host "==> Running act for case '$($case.Name)' (expect $($case.ExpectedVersion) / $($case.ExpectedType))" -ForegroundColor Cyan

    # --- Build an isolated temp git repo ---------------------------------
    $tmp = Join-Path ([System.IO.Path]::GetTempPath()) ("act-bump-" + $case.Name + "-" + [guid]::NewGuid().ToString('N').Substring(0, 8))
    New-Item -ItemType Directory -Path $tmp -Force | Out-Null
    try {
        New-Item -ItemType Directory -Path (Join-Path $tmp '.github/workflows') -Force | Out-Null

        foreach ($f in $ProjectFiles) {
            Copy-Item -LiteralPath (Join-Path $Root $f) -Destination $tmp
        }
        Copy-Item -LiteralPath (Join-Path $Root '.github/workflows/semantic-version-bumper.yml') `
                  -Destination (Join-Path $tmp '.github/workflows')
        # Bring the act platform mapping so act uses the prebuilt pwsh image.
        Copy-Item -LiteralPath (Join-Path $Root '.actrc') -Destination $tmp

        # Fixture data for this case.
        Set-Content -LiteralPath (Join-Path $tmp $case.VersionFileName) -Value $case.VersionContent -NoNewline
        Copy-Item -LiteralPath (Join-Path $Root $case.CommitFixture) -Destination (Join-Path $tmp 'commits.txt')

        # Initialise the git repo (act requires one; checkout@v4 uses it).
        git -C $tmp init -q -b main
        git -C $tmp config user.email 'ci@example.com'
        git -C $tmp config user.name  'CI'
        git -C $tmp add -A
        git -C $tmp commit -q -m "test: fixture for $($case.Name)"

        # --- Run the workflow through act --------------------------------
        Push-Location $tmp
        try {
            # --pull=false: the image is already present locally.
            $output = & act push --rm --pull=false 2>&1 | Out-String
            $actExit = $LASTEXITCODE
        } finally {
            Pop-Location
        }

        # --- Persist output (clearly delimited) --------------------------
        Add-Result ("=" * 78)
        Add-Result "CASE: $($case.Name)  (expected version=$($case.ExpectedVersion), type=$($case.ExpectedType))"
        Add-Result ("=" * 78)
        Add-Result $output
        Add-Result "ACT_EXIT_CODE=$actExit"
        Add-Result ""

        # --- Assertions --------------------------------------------------
        if ($actExit -ne 0) {
            $failures.Add("[$($case.Name)] act exited with $actExit (expected 0)")
        }

        $jobSucceeded = ([regex]::Matches($output, 'Job succeeded')).Count
        if ($jobSucceeded -lt 2) {
            $failures.Add("[$($case.Name)] expected >=2 'Job succeeded' (bump+report), saw $jobSucceeded")
        }

        if ($output -notmatch [regex]::Escape("NEW_VERSION=$($case.ExpectedVersion)")) {
            $failures.Add("[$($case.Name)] expected NEW_VERSION=$($case.ExpectedVersion) not found in output")
        }

        if ($output -notmatch [regex]::Escape("BUMP_TYPE=$($case.ExpectedType)")) {
            $failures.Add("[$($case.Name)] expected BUMP_TYPE=$($case.ExpectedType) not found in output")
        }

        # The report job consumes the bump job's output -> proves job wiring.
        if ($output -notmatch [regex]::Escape("REPORT_VERSION=$($case.ExpectedVersion)")) {
            $failures.Add("[$($case.Name)] expected REPORT_VERSION=$($case.ExpectedVersion) not found in output")
        }

        if ($actExit -eq 0 -and $jobSucceeded -ge 2 -and
            $output -match [regex]::Escape("NEW_VERSION=$($case.ExpectedVersion)")) {
            Write-Host "    PASS: $($case.Name)" -ForegroundColor Green
        } else {
            Write-Host "    FAIL: $($case.Name)" -ForegroundColor Red
        }
    }
    finally {
        Remove-Item -LiteralPath $tmp -Recurse -Force -ErrorAction SilentlyContinue
    }
}

# --- Summary -------------------------------------------------------------
Add-Result ("#" * 78)
if ($failures.Count -eq 0) {
    Add-Result "ALL ACT INTEGRATION CASES PASSED ($($Cases.Count) cases)"
    Write-Host "`nAll $($Cases.Count) act integration cases passed." -ForegroundColor Green
    Write-Host "Results written to: $ResultFile"
    exit 0
} else {
    Add-Result "FAILURES:"
    foreach ($f in $failures) { Add-Result " - $f" }
    Write-Host "`n$($failures.Count) failure(s):" -ForegroundColor Red
    $failures | ForEach-Object { Write-Host " - $_" -ForegroundColor Red }
    Write-Host "Results written to: $ResultFile"
    exit 1
}
