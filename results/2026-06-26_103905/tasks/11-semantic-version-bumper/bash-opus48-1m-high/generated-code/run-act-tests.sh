#!/usr/bin/env bash
#
# run-act-tests.sh — Integration test harness that runs EVERY test case through
# the GitHub Actions workflow via `act` (nektos/act), then asserts on the exact
# expected values found in the captured output.
#
# Why one act invocation for all cases?
#   The workflow uses a job matrix with one entry per scenario, so a single
#   `act push` runs all six cases as six separate jobs. This honours the
#   "at most 3 act push runs" guidance while still executing every case through
#   the real pipeline and producing an independent "Job succeeded" per case.
#
# Output contract:
#   * The full act log for every case is written (clearly delimited) to
#     act-result.txt in the directory this script is invoked from.
#   * The script exits non-zero if act fails, if any case's version does not
#     match its known-good expected value, or if any job did not succeed.

set -uo pipefail

# --- locations ------------------------------------------------------------
PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RESULT_FILE="${PROJECT_DIR}/act-result.txt"

# --- known-good expected values (case -> expected new version) ------------
# These are the exact values the harness asserts against the parsed act output.
declare -A EXPECTED=(
  [patch]=1.1.1
  [minor]=1.2.0
  [major]=2.0.0
  [pkgjson]=0.4.0
  [breaking-footer]=3.0.0
  [none]=1.1.0
)
EXPECTED_JOBS=${#EXPECTED[@]}

# --- set up an isolated temp git repo with the project files --------------
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

echo "[harness] staging project into temp git repo: $WORK"
cp -r "${PROJECT_DIR}/semver-bump.sh" \
      "${PROJECT_DIR}/fixtures" \
      "${PROJECT_DIR}/.github" \
      "${PROJECT_DIR}/.actrc" \
      "$WORK/"
chmod +x "$WORK/semver-bump.sh"

(
  cd "$WORK" || exit 1
  git init -q
  git config user.email "ci@example.com"
  git config user.name "CI"
  git add -A
  git commit -q -m "test: stage semantic-version-bumper for act"
)

# --- run the workflow through act (single push, all matrix jobs) ----------
echo "[harness] running: act push --rm --pull=false"
ACT_LOG="$(mktemp)"
(
  cd "$WORK" || exit 1
  # --pull=false: the act-ubuntu-pwsh image is already present locally.
  act push --rm --pull=false -W .github/workflows/semantic-version-bumper.yml
) >"$ACT_LOG" 2>&1
ACT_RC=$?

# --- persist the full output to the required artifact ---------------------
{
  echo "############################################################"
  echo "# act-result.txt — Semantic Version Bumper integration run"
  echo "# Generated by run-act-tests.sh (single 'act push' over the job matrix)"
  echo "# act exit code: ${ACT_RC}"
  echo "############################################################"
  echo
  cat "$ACT_LOG"
  echo
} > "$RESULT_FILE"

echo "[harness] full act output saved to: $RESULT_FILE"

# --- assertions -----------------------------------------------------------
FAILURES=0

# 1) act must have exited 0.
if [[ "$ACT_RC" -eq 0 ]]; then
  echo "[PASS] act exited 0"
else
  echo "[FAIL] act exited with non-zero status: $ACT_RC"
  FAILURES=$((FAILURES + 1))
fi

# 2) Each test case must show its EXACT expected version in the parsed output.
#    The workflow prints "RESULT case=<name> new_version=<ver>" per job.
{
  echo "------------------------------------------------------------"
  echo "# Per-case assertions (exact expected values)"
  echo "------------------------------------------------------------"
} >> "$RESULT_FILE"

for case_name in "${!EXPECTED[@]}"; do
  want="${EXPECTED[$case_name]}"
  # Extract the new_version reported for this case (strip any act line prefix).
  got="$(grep -oE "RESULT case=${case_name} new_version=[0-9]+\.[0-9]+\.[0-9]+" "$ACT_LOG" \
         | head -n1 | sed -E 's/.*new_version=//')"
  if [[ "$got" == "$want" ]]; then
    msg="[PASS] case=${case_name}: expected ${want}, got ${got}"
  else
    msg="[FAIL] case=${case_name}: expected ${want}, got '${got:-<none>}'"
    FAILURES=$((FAILURES + 1))
  fi
  echo "$msg"
  echo "$msg" >> "$RESULT_FILE"
done

# 3) Every job must report success. act prints "Job succeeded" per job.
SUCCEEDED="$(grep -c "Job succeeded" "$ACT_LOG" || true)"
if [[ "$SUCCEEDED" -eq "$EXPECTED_JOBS" ]]; then
  msg="[PASS] all ${EXPECTED_JOBS} jobs reported 'Job succeeded'"
else
  msg="[FAIL] expected ${EXPECTED_JOBS} 'Job succeeded', found ${SUCCEEDED}"
  FAILURES=$((FAILURES + 1))
fi
echo "$msg"
echo "$msg" >> "$RESULT_FILE"

# 4) No job may report failure.
if grep -q "Job failed" "$ACT_LOG"; then
  msg="[FAIL] at least one job reported 'Job failed'"
  FAILURES=$((FAILURES + 1))
  echo "$msg"
  echo "$msg" >> "$RESULT_FILE"
fi

rm -f "$ACT_LOG"

# --- verdict --------------------------------------------------------------
echo "------------------------------------------------------------"
if [[ "$FAILURES" -eq 0 ]]; then
  echo "[harness] ALL ASSERTIONS PASSED"
  echo "[harness] ALL ASSERTIONS PASSED" >> "$RESULT_FILE"
  exit 0
else
  echo "[harness] ${FAILURES} ASSERTION(S) FAILED"
  echo "[harness] ${FAILURES} ASSERTION(S) FAILED" >> "$RESULT_FILE"
  exit 1
fi
