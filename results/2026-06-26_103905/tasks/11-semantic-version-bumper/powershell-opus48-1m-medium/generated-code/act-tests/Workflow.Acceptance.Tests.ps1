# Workflow.Acceptance.Tests.ps1
#
# End-to-end acceptance tests that exercise the ENTIRE GitHub Actions workflow
# through `act` (nektos/act) — no direct script invocation. For each fixture we:
#   1. build an isolated temp git repo containing the project files + the
#      fixture's version/commit data,
#   2. run `act push --rm` against it,
#   3. capture the output (appended to act-result.txt, clearly delimited),
#   4. assert exit code 0, the EXACT expected new version, and "Job succeeded".
#
# Plus structural tests: YAML parsing, script-reference existence, actionlint.
#
# Run from the project root:  Invoke-Pester -Path ./act-tests

# NOTE: This array is declared at the top level (not inside BeforeAll) so it is
# available during Pester's DISCOVERY phase, which is when `-ForEach` on the It
# blocks is expanded. Expected values are exact and derived by hand from each
# fixture (conventional-commit rules + semver).
$Cases = @(
    @{ Name = 'feat-minor';      Fixture = 'feat-minor';      Old = '1.1.0'; New = '1.2.0'; Bump = 'minor' }
    @{ Name = 'fix-patch';       Fixture = 'fix-patch';       Old = '2.3.4'; New = '2.3.5'; Bump = 'patch' }
    @{ Name = 'breaking-major';  Fixture = 'breaking-major';  Old = '1.4.2'; New = '2.0.0'; Bump = 'major' }
    @{ Name = 'pkgjson-minor';   Fixture = 'pkgjson-minor';   Old = '0.5.0'; New = '0.6.0'; Bump = 'minor' }
)

BeforeAll {
    # Re-declare the case matrix here as well: Pester runs top-level statements
    # only during DISCOVERY, so the discovery-scope $Cases above is not in scope
    # at RUN time when this BeforeAll body executes. Keep the two in sync.
    $Cases = @(
        @{ Name = 'feat-minor';      Fixture = 'feat-minor';      Old = '1.1.0'; New = '1.2.0'; Bump = 'minor' }
        @{ Name = 'fix-patch';       Fixture = 'fix-patch';       Old = '2.3.4'; New = '2.3.5'; Bump = 'patch' }
        @{ Name = 'breaking-major';  Fixture = 'breaking-major';  Old = '1.4.2'; New = '2.0.0'; Bump = 'major' }
        @{ Name = 'pkgjson-minor';   Fixture = 'pkgjson-minor';   Old = '0.5.0'; New = '0.6.0'; Bump = 'minor' }
    )

    $ProjectRoot = Split-Path -Parent $PSScriptRoot
    $ResultFile  = Join-Path $ProjectRoot 'act-result.txt'

    # Start each run with a fresh aggregate log.
    Set-Content -LiteralPath $ResultFile -Value "act-result.txt — generated by act-tests/Workflow.Acceptance.Tests.ps1`n"

    # Helper: stage a temp git repo with project files + a fixture, then run act.
    function Invoke-ActCase {
        param(
            [string]$CaseName,
            [string]$FixtureDir,   # absolute path to the fixture directory
            [string]$ProjectRoot,
            [string]$ResultFile
        )

        $work = Join-Path ([System.IO.Path]::GetTempPath()) "svb-act-$CaseName"
        if (Test-Path $work) { Remove-Item -Recurse -Force $work }
        New-Item -ItemType Directory -Path $work -Force | Out-Null

        # Copy the project files the workflow depends on.
        foreach ($item in @('SemanticVersionBumper.psm1', 'Invoke-VersionBump.ps1', 'tests', '.github', '.actrc')) {
            Copy-Item -Path (Join-Path $ProjectRoot $item) -Destination $work -Recurse -Force
        }
        # Copy the fixture data (version.txt or package.json, and commits.txt).
        Copy-Item -Path (Join-Path $FixtureDir '*') -Destination $work -Recurse -Force

        # act requires a git repo to resolve the event/ref.
        Push-Location $work
        try {
            git init -q 2>&1 | Out-Null
            git add -A 2>&1 | Out-Null
            git -c user.email='ci@example.com' -c user.name='ci' commit -qm 'fixture' 2>&1 | Out-Null

            # Run the full workflow on a push event in an ephemeral container.
            $raw = & act push --rm 2>&1
            $exit = $LASTEXITCODE
            $output = ($raw | Out-String)
        }
        finally {
            Pop-Location
        }

        # Append this case's output to the aggregate artifact, delimited.
        $banner = "`n================ CASE: $CaseName (act exit=$exit) ================`n"
        Add-Content -LiteralPath $ResultFile -Value $banner
        Add-Content -LiteralPath $ResultFile -Value $output

        return [PSCustomObject]@{ Exit = $exit; Output = $output; WorkDir = $work }
    }

    # Run every case once up front; the It blocks then assert on cached results.
    # $Cases comes from the top-level (discovery-scope) declaration above.
    $script:Results = @{}
    foreach ($c in $Cases) {
        $fixtureDir = Join-Path $ProjectRoot (Join-Path 'fixtures' $c.Fixture)
        $script:Results[$c.Name] = Invoke-ActCase -CaseName $c.Name -FixtureDir $fixtureDir `
            -ProjectRoot $ProjectRoot -ResultFile $ResultFile
    }
}

Describe 'Workflow structure' {
    BeforeAll {
        $script:WorkflowPath = Join-Path (Split-Path -Parent $PSScriptRoot) '.github/workflows/semantic-version-bumper.yml'
        $script:WorkflowText = Get-Content -LiteralPath $script:WorkflowPath -Raw
    }

    It 'workflow file exists' {
        Test-Path $script:WorkflowPath | Should -BeTrue
    }

    It 'declares the expected trigger events' {
        $script:WorkflowText | Should -Match '(?m)^\s*push:'
        $script:WorkflowText | Should -Match '(?m)^\s*pull_request:'
        $script:WorkflowText | Should -Match '(?m)^\s*schedule:'
        $script:WorkflowText | Should -Match '(?m)^\s*workflow_dispatch:'
    }

    It 'declares permissions' {
        $script:WorkflowText | Should -Match '(?m)^permissions:'
        $script:WorkflowText | Should -Match 'contents:\s*read'
    }

    It 'defines a job that runs on ubuntu-latest' {
        $script:WorkflowText | Should -Match '(?m)^\s*bump:'
        $script:WorkflowText | Should -Match 'runs-on:\s*ubuntu-latest'
    }

    It 'checks out the repo with actions/checkout@v4' {
        $script:WorkflowText | Should -Match 'actions/checkout@v4'
    }

    It 'references the project scripts that actually exist on disk' {
        $root = Split-Path -Parent $PSScriptRoot
        $script:WorkflowText | Should -Match 'Invoke-VersionBump\.ps1'
        Test-Path (Join-Path $root 'Invoke-VersionBump.ps1')   | Should -BeTrue
        Test-Path (Join-Path $root 'SemanticVersionBumper.psm1') | Should -BeTrue
    }

    It 'uses shell: pwsh for run steps' {
        $script:WorkflowText | Should -Match 'shell:\s*pwsh'
    }

    It 'passes actionlint cleanly (exit 0)' {
        $null = & actionlint $script:WorkflowPath 2>&1
        $LASTEXITCODE | Should -Be 0
    }
}

Describe 'act end-to-end execution' {
    It '<Name>: act exits 0' -ForEach $Cases {
        $script:Results[$Name].Exit | Should -Be 0
    }

    It '<Name>: every job reports "Job succeeded"' -ForEach $Cases {
        $script:Results[$Name].Output | Should -Match 'Job succeeded'
    }

    It '<Name>: reads the exact old version <Old>' -ForEach $Cases {
        $script:Results[$Name].Output | Should -Match "OLD_VERSION=$([regex]::Escape($Old))"
    }

    It '<Name>: produces the EXACT new version <New>' -ForEach $Cases {
        $script:Results[$Name].Output | Should -Match "NEW_VERSION=$([regex]::Escape($New))"
    }

    It '<Name>: reports the exact bump type <Bump>' -ForEach $Cases {
        $script:Results[$Name].Output | Should -Match "BUMP_TYPE=$([regex]::Escape($Bump))"
    }
}

Describe 'act-result.txt artifact' {
    It 'exists and contains output for every case' {
        $resultFile = Join-Path (Split-Path -Parent $PSScriptRoot) 'act-result.txt'
        Test-Path $resultFile | Should -BeTrue
        $text = Get-Content -LiteralPath $resultFile -Raw
        # Names listed inline so this assertion does not depend on a
        # discovery-scope variable at run time.
        foreach ($name in @('feat-minor', 'fix-patch', 'breaking-major', 'pkgjson-minor')) {
            $text | Should -Match "CASE: $name"
        }
    }
}
