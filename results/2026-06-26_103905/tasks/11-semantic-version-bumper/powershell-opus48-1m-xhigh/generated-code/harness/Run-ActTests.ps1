#Requires -Version 7.0

<#
.SYNOPSIS
    Integration harness: runs the semantic-version-bumper workflow through
    `act` (a real GitHub Actions runner in Docker) once per test fixture and
    asserts on the exact expected output.

.DESCRIPTION
    For each requested case this harness:
      1. builds an isolated temporary git repository containing the project
         files plus that case's fixture data (VERSION + commits.txt),
      2. runs `act push --rm` against the workflow,
      3. appends the full, delimited act output to act-result.txt,
      4. asserts act exited 0, that both jobs report "Job succeeded", and that
         the output contains the EXACT expected version / bump type / changelog
         lines for that fixture.

    Expected values come from fixtures/<case>/expected.json so the assertions
    are data-driven and easy to audit.

.PARAMETER Cases
    Which fixtures (folder names under ./fixtures) to drive through act.
    Defaults to the three canonical bump scenarios. Each case uses a plain
    VERSION file (the workflow's default source), so they all exercise the same
    pipeline with different inputs.

.PARAMETER Append
    Append to an existing act-result.txt instead of truncating it first.

.OUTPUTS
    Exit code 0 when every case passes every assertion, 1 otherwise.
#>
[CmdletBinding()]
param(
    [string[]] $Cases = @('minor-feature', 'patch-fix', 'major-breaking'),
    [switch]   $Append
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

# --- Paths -----------------------------------------------------------------
$ProjectRoot = Split-Path $PSScriptRoot -Parent
$ResultFile  = Join-Path $ProjectRoot 'act-result.txt'
$Workflow    = '.github/workflows/semantic-version-bumper.yml'
$Image       = 'act-ubuntu-pwsh:latest'

# Files/dirs copied into each disposable test repo.
$ProjectFiles = @(
    'Invoke-VersionBump.ps1',
    'SemanticVersionBumper.psm1',
    '.actrc',
    'tests',
    '.github'
)

function Write-Banner {
    param([string] $Text)
    Write-Host ''
    Write-Host ('=' * 80)
    Write-Host $Text
    Write-Host ('=' * 80)
}

# --- Pre-flight checks -----------------------------------------------------
foreach ($tool in 'act', 'docker', 'git') {
    if (-not (Get-Command $tool -ErrorAction SilentlyContinue)) {
        throw "Required tool '$tool' is not on PATH."
    }
}
& docker image inspect $Image *> $null
if ($LASTEXITCODE -ne 0) {
    throw "Required act container image '$Image' is not present. Build it with: docker build -t $Image -f Dockerfile.act ."
}

# Truncate the result file unless appending.
if (-not $Append) {
    $header = @(
        "Semantic Version Bumper - act integration results",
        "Generated by harness/Run-ActTests.ps1",
        "Cases: $($Cases -join ', ')"
    ) -join "`n"
    Set-Content -LiteralPath $ResultFile -Value ($header + "`n")
}

# --- Per-case runner -------------------------------------------------------
$results = [System.Collections.Generic.List[object]]::new()

foreach ($case in $Cases) {
    $caseDir = Join-Path $ProjectRoot "fixtures/$case"
    if (-not (Test-Path $caseDir)) { throw "Fixture not found: $caseDir" }

    $expected = Get-Content (Join-Path $caseDir 'expected.json') -Raw | ConvertFrom-Json

    Write-Banner "CASE: $case  (expect $($expected.previousVersion) -> $($expected.newVersion), bump=$($expected.bumpType))"

    # 1. Build an isolated git repo with project files + this case's fixtures.
    $repo = Join-Path ([System.IO.Path]::GetTempPath()) ("svb-" + $case + "-" + (New-Guid).ToString('N').Substring(0, 8))
    New-Item -ItemType Directory -Path $repo -Force | Out-Null
    try {
        foreach ($item in $ProjectFiles) {
            Copy-Item -Path (Join-Path $ProjectRoot $item) -Destination $repo -Recurse -Force
        }
        # Fixture data drives the workflow (always read as ./VERSION + ./commits.txt).
        Copy-Item -Path (Join-Path $caseDir 'VERSION')     -Destination (Join-Path $repo 'VERSION')     -Force
        Copy-Item -Path (Join-Path $caseDir 'commits.txt') -Destination (Join-Path $repo 'commits.txt') -Force
        # Start from a minimal changelog so the new entry is prepended.
        Set-Content -LiteralPath (Join-Path $repo 'CHANGELOG.md') -Value "# Changelog`n"

        # Deterministic push event so the branch filter (main/master) always matches.
        $event = @{
            ref        = 'refs/heads/main'
            repository = @{ name = 'svb-test'; full_name = 'test/svb-test'; default_branch = 'main' }
            pusher     = @{ name = 'tester'; email = 'tester@example.com' }
        } | ConvertTo-Json -Depth 5
        Set-Content -LiteralPath (Join-Path $repo 'push-event.json') -Value $event

        # 2. Commit so checkout@v4 has a real HEAD to work from.
        Push-Location $repo
        try {
            & git init -b main *> $null
            & git config user.email 'tester@example.com' *> $null
            & git config user.name  'SVB Tester'         *> $null
            & git add -A *> $null
            & git commit -m 'test fixture' *> $null

            # 3. Run the workflow through act (single push run per case).
            $argList = @(
                'push',
                '-W', $Workflow,
                '-e', 'push-event.json',
                '--pull=false',
                '--rm'
            )
            Write-Host "Running: act $($argList -join ' ')"
            $env:NO_COLOR = '1'
            $output  = & act @argList 2>&1 | Out-String
            $exit    = $LASTEXITCODE
        }
        finally {
            Pop-Location
        }

        # 4. Persist the output, clearly delimited, to act-result.txt.
        $block = @(
            ('#' * 80),
            "TEST CASE: $case",
            "Description: $($expected.description)",
            "Command: act $($argList -join ' ')   (cwd: $repo)",
            "Exit code: $exit",
            ('-' * 80),
            $output.TrimEnd(),
            ('#' * 80),
            ''
        ) -join "`n"
        Add-Content -LiteralPath $ResultFile -Value $block

        # 5. Assertions on EXACT expected values.
        $failures = [System.Collections.Generic.List[string]]::new()

        if ($exit -ne 0) { $failures.Add("act exit code was $exit (expected 0)") }

        # Both jobs (test + bump) must report success; none may fail.
        $succeeded = ([regex]::Matches($output, 'Job succeeded')).Count
        if ($succeeded -lt 2) { $failures.Add("found $succeeded 'Job succeeded' lines (expected >= 2, one per job)") }
        if ($output -match 'Job failed') { $failures.Add("output contains 'Job failed'") }

        # Exact PREVIOUS_VERSION / BUMP_TYPE / NEW_VERSION (not followed by another digit).
        $checks = @{
            'PREVIOUS_VERSION' = $expected.previousVersion
            'BUMP_TYPE'        = $expected.bumpType
            'NEW_VERSION'      = $expected.newVersion
        }
        foreach ($key in $checks.Keys) {
            $val = [string] $checks[$key]
            $pattern = "$key=" + [regex]::Escape($val) + '(\D|$)'
            if ($output -notmatch $pattern) {
                $failures.Add("expected line '$key=$val' not found in act output")
            }
        }

        # The "Show the result" step echoes the consumed step output.
        $resultPattern = 'RESULT new-version=' + [regex]::Escape([string]$expected.newVersion)
        if ($output -notmatch $resultPattern) {
            $failures.Add("expected 'RESULT new-version=$($expected.newVersion)' (step output consumption) not found")
        }

        # Changelog content must include each expected entry.
        foreach ($needle in @($expected.changelogMustContain)) {
            if ($output -notmatch [regex]::Escape([string]$needle)) {
                $failures.Add("changelog entry '$needle' not present in act output")
            }
        }

        $passed = ($failures.Count -eq 0)
        if ($passed) {
            Write-Host "PASS: $case (new version $($expected.newVersion))" -ForegroundColor Green
        } else {
            Write-Host "FAIL: $case" -ForegroundColor Red
            $failures | ForEach-Object { Write-Host "  - $_" -ForegroundColor Red }
        }
        $results.Add([pscustomobject]@{ Case = $case; Passed = $passed; Failures = $failures; Exit = $exit })
    }
    finally {
        Remove-Item -LiteralPath $repo -Recurse -Force -ErrorAction SilentlyContinue
    }
}

# --- Summary ---------------------------------------------------------------
Write-Banner 'SUMMARY'
foreach ($r in $results) {
    $status = if ($r.Passed) { 'PASS' } else { 'FAIL' }
    Write-Host ("{0,-4}  {1}" -f $status, $r.Case)
}
Write-Host ''
Write-Host "Full act output saved to: $ResultFile"

$failed = @($results | Where-Object { -not $_.Passed })
if ($failed.Count -gt 0) {
    Write-Host "`n$($failed.Count) case(s) failed." -ForegroundColor Red
    exit 1
}
Write-Host "`nAll $($results.Count) case(s) passed." -ForegroundColor Green
exit 0
