#Requires -Modules Pester

<#
    Workflow tests for .github/workflows/semantic-version-bumper.yml.

    Two groups:

      1. 'Workflow file structure' - parses the YAML and asserts the expected
         triggers/jobs/steps, checks that the referenced script files exist, and
         asserts actionlint passes. These are fast and have no external deps.

      2. 'Workflow execution via act' (-Tag Act) - the required end-to-end suite.
         For each fixture case it builds a throwaway git repo containing the
         project files + that case's version file and commit log, runs
         `act push --rm` in a Docker container, appends the output to
         act-result.txt, and asserts on the EXACT next version, the bump type,
         and that every job reports "Job succeeded".

    Run everything:        Invoke-Pester ./Tests
    Structure tests only:  Invoke-Pester ./Tests/Workflow.Tests.ps1 -ExcludeTagFilter Act
#>

BeforeAll {
    $script:RepoRoot     = Split-Path $PSScriptRoot -Parent
    $script:WorkflowPath = Join-Path $script:RepoRoot '.github/workflows/semantic-version-bumper.yml'

    Import-Module powershell-yaml -ErrorAction Stop
    $script:Workflow = ConvertFrom-Yaml (Get-Content -LiteralPath $script:WorkflowPath -Raw)
}

Describe 'Workflow file structure' {

    It 'exists and parses as YAML' {
        Test-Path -LiteralPath $script:WorkflowPath | Should -BeTrue
        $script:Workflow | Should -Not -BeNullOrEmpty
    }

    It 'has the expected workflow name' {
        $script:Workflow['name'] | Should -Be 'Semantic Version Bumper'
    }

    It 'declares push, pull_request, schedule and workflow_dispatch triggers' {
        $on = $script:Workflow['on']
        $on.Keys | Should -Contain 'push'
        $on.Keys | Should -Contain 'pull_request'
        $on.Keys | Should -Contain 'schedule'
        $on.Keys | Should -Contain 'workflow_dispatch'
    }

    It 'uses a valid weekly cron schedule' {
        $script:Workflow['on']['schedule'][0]['cron'] | Should -Be '0 3 * * 1'
    }

    It 'declares least-privilege permissions (contents: read)' {
        $script:Workflow['permissions']['contents'] | Should -Be 'read'
    }

    It 'defines a test job and a bump job' {
        $script:Workflow['jobs'].Keys | Should -Contain 'test'
        $script:Workflow['jobs'].Keys | Should -Contain 'bump'
    }

    It 'makes the bump job depend on the test job (job dependency)' {
        $script:Workflow['jobs']['bump']['needs'] | Should -Be 'test'
    }

    It 'runs both jobs on ubuntu-latest' {
        $script:Workflow['jobs']['test']['runs-on'] | Should -Be 'ubuntu-latest'
        $script:Workflow['jobs']['bump']['runs-on'] | Should -Be 'ubuntu-latest'
    }

    It 'checks out the repo with actions/checkout@v4' {
        $uses = $script:Workflow['jobs'].Values |
            ForEach-Object { $_['steps'] } |
            ForEach-Object { $_['uses'] } |
            Where-Object { $_ }
        $uses | Should -Contain 'actions/checkout@v4'
    }

    It 'invokes the bumper script from a pwsh step' {
        $bumpSteps = $script:Workflow['jobs']['bump']['steps']
        # @(...) guards against Where-Object collapsing a single match to a scalar.
        $runStep = @($bumpSteps | Where-Object { $_['run'] -and ($_['run'] -match 'Update-SemanticVersion\.ps1') })
        $runStep.Count | Should -BeGreaterThan 0
        $runStep[0]['shell'] | Should -Be 'pwsh'
    }

    It 'references project files that actually exist on disk' {
        Test-Path -LiteralPath (Join-Path $script:RepoRoot 'Update-SemanticVersion.ps1') | Should -BeTrue
        Test-Path -LiteralPath (Join-Path $script:RepoRoot 'SemVerBumper.psm1')          | Should -BeTrue
    }

    It 'passes actionlint with no errors' {
        $output = & actionlint $script:WorkflowPath 2>&1
        $code = $LASTEXITCODE
        if ($code -ne 0) { Write-Host ($output | Out-String) }
        $code | Should -Be 0
    }
}

Describe 'Workflow execution via act' -Tag 'Act' {

    BeforeAll {
        # Required artifact: collect every case's act output here, in the CWD /
        # repo root, clearly delimited. Start fresh for this run.
        $script:ResultFile = Join-Path $script:RepoRoot 'act-result.txt'
        $header = "Semantic Version Bumper - act integration results`n" +
                  "Generated by Tests/Workflow.Tests.ps1`n" +
                  ('=' * 70) + "`n"
        Set-Content -LiteralPath $script:ResultFile -Value $header -Encoding utf8

        if (-not (Get-Command act -ErrorAction SilentlyContinue)) {
            throw "The 'act' CLI is required for the integration tests but was not found on PATH."
        }

        # Build a throwaway git repo (under the system temp dir, outside this repo)
        # containing the project files plus a single test case's fixture data.
        function New-ActRepo {
            param(
                [string]$VersionFileName,
                [string]$VersionContent,
                [string]$FixtureFile
            )
            $repo = Join-Path ([System.IO.Path]::GetTempPath()) ('act-svb-' + [guid]::NewGuid().ToString('N'))
            New-Item -ItemType Directory -Path $repo | Out-Null
            New-Item -ItemType Directory -Path (Join-Path $repo '.github/workflows') | Out-Null
            New-Item -ItemType Directory -Path (Join-Path $repo 'Tests') | Out-Null

            # Project files the workflow needs at runtime.
            Copy-Item (Join-Path $script:RepoRoot 'SemVerBumper.psm1')          $repo
            Copy-Item (Join-Path $script:RepoRoot 'Update-SemanticVersion.ps1') $repo
            Copy-Item (Join-Path $script:RepoRoot '.actrc')                     $repo
            Copy-Item (Join-Path $script:RepoRoot '.github/workflows/semantic-version-bumper.yml') (Join-Path $repo '.github/workflows')
            # Unit-test files the in-container 'test' job runs.
            Copy-Item (Join-Path $script:RepoRoot 'Tests/SemVerBumper.Tests.ps1')          (Join-Path $repo 'Tests')
            Copy-Item (Join-Path $script:RepoRoot 'Tests/UpdateSemanticVersion.Tests.ps1') (Join-Path $repo 'Tests')

            # The case-specific inputs.
            Set-Content -Path (Join-Path $repo $VersionFileName) -Value $VersionContent -Encoding utf8
            Copy-Item (Join-Path $script:RepoRoot "fixtures/$FixtureFile") (Join-Path $repo 'commits.txt')

            return $repo
        }

        # Initialise git in the repo and run the push workflow through act.
        function Invoke-ActCase {
            param([string]$Repo)
            Push-Location $Repo
            try {
                & git init -q -b main 2>&1 | Out-Null
                & git config user.email 'ci@example.com' 2>&1 | Out-Null
                & git config user.name  'ci' 2>&1 | Out-Null
                & git config commit.gpgsign false 2>&1 | Out-Null
                & git add -A 2>&1 | Out-Null
                & git commit -q -m 'test fixture' 2>&1 | Out-Null

                # --pull=false: the runner image (act-ubuntu-pwsh:latest) is a
                # local-only build; act's default forcePull would try to pull it
                # from a registry and fail at "Set up job". The copied .actrc also
                # sets this, but we pass it explicitly so the case is robust.
                $out = & act push --rm --pull=false 2>&1 | Out-String
                $code = $LASTEXITCODE
            } finally {
                Pop-Location
            }
            [pscustomobject]@{ Output = $out; Exit = $code }
        }

        # Record a case's result to the required artifact file.
        function Save-ActResult {
            param([string]$Name, $Result)
            $block = "`n" + ('=' * 70) + "`nCASE: $Name`nact exit code: $($Result.Exit)`n" +
                     ('-' * 70) + "`n" + $Result.Output + "`n"
            Add-Content -LiteralPath $script:ResultFile -Value $block -Encoding utf8
        }
    }

    # One row per test case: starting version -> expected next version. Both plain
    # VERSION files and a package.json are covered, across all three bump levels.
    $cases = @(
        @{ Name = 'feat commit bumps the minor';              VersionFileName = 'VERSION';      VersionContent = '1.1.0';                                  Fixture = 'commits-feat.txt';     Expected = '1.2.0'; ExpectedBump = 'minor' }
        @{ Name = 'fix commit bumps the patch';               VersionFileName = 'VERSION';      VersionContent = '1.4.2';                                  Fixture = 'commits-fix.txt';      Expected = '1.4.3'; ExpectedBump = 'patch' }
        @{ Name = 'breaking change bumps major (package.json)'; VersionFileName = 'package.json'; VersionContent = '{ "name": "demo", "version": "2.5.1" }'; Fixture = 'commits-breaking.txt'; Expected = '3.0.0'; ExpectedBump = 'major' }
    )

    It '<Name>' -ForEach $cases {
        $repo = New-ActRepo -VersionFileName $VersionFileName -VersionContent $VersionContent -FixtureFile $Fixture
        try {
            $result = Invoke-ActCase -Repo $repo
        } finally {
            Save-ActResult -Name $Name -Result $result
            Remove-Item -LiteralPath $repo -Recurse -Force -ErrorAction SilentlyContinue
        }

        # 1. act ran the whole pipeline successfully.
        $result.Exit | Should -Be 0 -Because "act push should succeed for case '$Name'"

        # 2. Every job (test + bump) reported success; none failed.
        $result.Output | Should -Not -Match 'Job failed'
        ([regex]::Matches($result.Output, 'Job succeeded')).Count |
            Should -BeGreaterOrEqual 2 -Because 'both the test and bump jobs must succeed'

        # 3. EXACT expected values. -CMatch is case-SENSITIVE so the uppercase
        #    script line and the lowercase report/GITHUB_OUTPUT line are asserted
        #    distinctly (a case-insensitive -Match would let one satisfy both).
        # ...the script's own output line...
        $result.Output | Should -CMatch ([regex]::Escape("NEW_VERSION=$Expected"))
        $result.Output | Should -CMatch ([regex]::Escape("BUMP_TYPE=$ExpectedBump"))
        # ...and the GITHUB_OUTPUT round-trip surfaced by the report step.
        $result.Output | Should -CMatch ([regex]::Escape("new_version=$Expected"))
        $result.Output | Should -CMatch ([regex]::Escape("bump_type=$ExpectedBump"))
    }

    It 'produced the act-result.txt artifact with every case recorded' {
        Test-Path -LiteralPath $script:ResultFile | Should -BeTrue
        $content = Get-Content -LiteralPath $script:ResultFile -Raw
        $content | Should -Match 'CASE: feat commit bumps the minor'
        $content | Should -Match 'CASE: fix commit bumps the patch'
        $content | Should -Match 'CASE: breaking change bumps major'
    }
}
