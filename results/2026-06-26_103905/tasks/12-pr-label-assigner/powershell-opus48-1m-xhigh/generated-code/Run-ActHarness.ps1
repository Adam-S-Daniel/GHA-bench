#!/usr/bin/env pwsh
<#
.SYNOPSIS
    End-to-end test harness. Runs every test case through the GitHub Actions
    workflow using `act` (nektos/act), captures all output to act-result.txt,
    and asserts EXACT expected results.

.DESCRIPTION
    For each test case this harness:
      1. Builds an isolated temp git repo containing the project files plus that
         case's changed-files fixture (placed at fixtures/changed-files.txt).
      2. Runs `act push --rm` in that repo and captures the combined output.
      3. Appends the output to act-result.txt (clearly delimited per case).
      4. Asserts: act exit code == 0; the EXACT PR_LABELS / PR_LABEL_COUNT
         marker lines for that case appear; and every job shows "Job succeeded".

    Exits 0 only if every case passes.

.PARAMETER Cases
    Optional subset of case names to run (e.g. for a quick smoke test).
#>
[CmdletBinding()]
param(
    [string[]]$Cases
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
# Capture native (act/git) non-zero exits explicitly instead of having them throw.
$PSNativeCommandUseErrorActionPreference = $false

$ProjectRoot = $PSScriptRoot
$ResultFile  = Join-Path $ProjectRoot 'act-result.txt'

# --- Test cases: each fixture maps to the EXACT label set the workflow must
#     produce. These exact values are what we assert against the act output. ---
$testCases = @(
    [pscustomobject]@{
        Name           = '01-mixed'
        Fixture        = 'fixtures/cases/01-mixed.txt'
        ExpectedLabels = 'tests,dependencies,api,backend,source,documentation'
        ExpectedCount  = 6
    }
    [pscustomobject]@{
        Name           = '02-exclusive'
        Fixture        = 'fixtures/cases/02-exclusive.txt'
        ExpectedLabels = 'generated,api,backend,source,documentation'
        ExpectedCount  = 5
    }
    [pscustomobject]@{
        Name           = '03-docs-only'
        Fixture        = 'fixtures/cases/03-docs-only.txt'
        ExpectedLabels = 'documentation'
        ExpectedCount  = 1
    }
)

if ($Cases) {
    $testCases = @($testCases | Where-Object { $_.Name -in $Cases })
    if ($testCases.Count -eq 0) { throw "No matching test cases for: $($Cases -join ', ')" }
}

# Project artifacts copied into each isolated temp repo.
$artifacts = @('src', 'tests', 'fixtures', '.github', 'Invoke-PrLabelAssigner.ps1', '.actrc')

# Start a fresh result file.
Set-Content -Path $ResultFile -Encoding utf8 -Value @"
PR Label Assigner -- act integration results
Generated by Run-ActHarness.ps1
Cases: $($testCases.Name -join ', ')

"@

function Add-Result { param([string]$Text) Add-Content -Path $ResultFile -Value $Text -Encoding utf8 }

$failures = [System.Collections.Generic.List[string]]::new()

foreach ($case in $testCases) {
    Write-Host "=== Running case: $($case.Name) ===" -ForegroundColor Cyan

    # 1. Isolated temp git repo = project files + this case's fixture data.
    $tmp = Join-Path ([System.IO.Path]::GetTempPath()) ("pr-label-act-$($case.Name)-" + [guid]::NewGuid().ToString('N').Substring(0, 8))
    New-Item -ItemType Directory -Path $tmp -Force | Out-Null
    try {
        foreach ($item in $artifacts) {
            $src = Join-Path $ProjectRoot $item
            if (Test-Path -LiteralPath $src) {
                Copy-Item -LiteralPath $src -Destination $tmp -Recurse -Force
            }
        }
        # Overwrite the manifest the workflow reads with this case's data.
        Copy-Item -LiteralPath (Join-Path $ProjectRoot $case.Fixture) `
                  -Destination (Join-Path $tmp 'fixtures/changed-files.txt') -Force

        Push-Location $tmp
        try {
            # actions/checkout@v4 needs a committed HEAD to check out.
            git init -q -b main 2>&1 | Out-Null
            git config user.email 'harness@example.com' | Out-Null
            git config user.name  'act harness'         | Out-Null
            git add -A 2>&1 | Out-Null
            git commit -q -m "case $($case.Name)" 2>&1 | Out-Null

            # 2. Run the workflow via act, capturing combined stdout+stderr.
            #    --pull=false: use the local custom image; do not hit a registry.
            $actOutput = (& act push --rm --pull=false 2>&1 | Out-String)
            $actExit   = $LASTEXITCODE
        }
        finally {
            Pop-Location
        }

        # 2b. Append clearly-delimited output to act-result.txt.
        Add-Result ('=' * 80)
        Add-Result "CASE: $($case.Name)    fixture=$($case.Fixture)"
        Add-Result "EXPECTED: PR_LABELS=$($case.ExpectedLabels)   PR_LABEL_COUNT=$($case.ExpectedCount)"
        Add-Result "act exit code: $actExit"
        Add-Result ('-' * 80)
        Add-Result $actOutput

        # 3-5. Assertions.
        $caseFailed = $false
        if ($actExit -ne 0) {
            $failures.Add("$($case.Name): act exit code $actExit (expected 0)"); $caseFailed = $true
        }

        $markerLabels = "PR_LABELS=$($case.ExpectedLabels)"
        if ($actOutput -notmatch [regex]::Escape($markerLabels)) {
            $failures.Add("$($case.Name): expected marker '$markerLabels' not found in act output"); $caseFailed = $true
        }

        $markerCount = "PR_LABEL_COUNT=$($case.ExpectedCount)"
        if ($actOutput -notmatch [regex]::Escape($markerCount)) {
            $failures.Add("$($case.Name): expected '$markerCount' not found in act output"); $caseFailed = $true
        }

        # Two jobs (test, assign-labels) must both succeed.
        $succeeded = ([regex]::Matches($actOutput, 'Job succeeded')).Count
        if ($succeeded -lt 2) {
            $failures.Add("$($case.Name): expected >=2 'Job succeeded', found $succeeded"); $caseFailed = $true
        }

        $verdict = if ($caseFailed) { 'FAILED' } else { 'PASSED' }
        Add-Result "VERDICT: $verdict  (jobs succeeded: $succeeded)"
        Add-Result ''
        if ($caseFailed) { Write-Host "  $verdict" -ForegroundColor Red }
        else { Write-Host "  $verdict  labels=$($case.ExpectedLabels)" -ForegroundColor Green }
    }
    finally {
        Remove-Item -LiteralPath $tmp -Recurse -Force -ErrorAction SilentlyContinue
    }
}

# Final summary.
Add-Result ('=' * 80)
if ($failures.Count -eq 0) {
    Add-Result "RESULT: ALL $($testCases.Count) CASE(S) PASSED"
    Write-Host "`nAll $($testCases.Count) case(s) passed. Full output -> $ResultFile" -ForegroundColor Green
    exit 0
}
else {
    Add-Result "RESULT: $($failures.Count) FAILURE(S):"
    foreach ($f in $failures) { Add-Result "  - $f" }
    Write-Host "`n$($failures.Count) failure(s):" -ForegroundColor Red
    foreach ($f in $failures) { Write-Host "  - $f" -ForegroundColor Red }
    exit 1
}
