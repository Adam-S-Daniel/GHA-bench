#!/usr/bin/env bun
/**
 * act integration harness for the PR Label Assigner workflow.
 *
 * For each test case this:
 *   1. Builds a temp git repo containing the project + that case's fixture
 *      (fixtures/changed-files.txt is overwritten with the case's file list).
 *   2. Runs `act push --rm` inside it, capturing all output.
 *   3. Appends the output to act-result.txt (clearly delimited per case).
 *   4. Asserts: act exit code 0, the workflow's `Job succeeded` marker is
 *      present, and the computed `LABELS=` line EXACTLY matches the known-good
 *      value for that case's input.
 *
 * Run with: bun run run-act-tests.ts
 * Exits non-zero if any case fails.
 */
import { spawnSync } from "node:child_process";
import {
  cpSync,
  mkdtempSync,
  rmSync,
  writeFileSync,
  appendFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const PROJECT_ROOT = import.meta.dir;
const RESULT_FILE = join(PROJECT_ROOT, "act-result.txt");

interface ActCase {
  name: string;
  /** Newline-delimited changed-file list written into fixtures/changed-files.txt */
  fixture: string;
  /** EXACT expected value of the LABELS= line emitted by the workflow. */
  expectedLabels: string;
}

// Known-good cases. Expected values verified against the committed config
// (.github/labeler-config.json) and the labeler's priority ordering.
const CASES: ActCase[] = [
  {
    name: "api-tests-code",
    fixture: "src/api/users.test.ts\nsrc/api/index.ts\n",
    // api(10) > tests(5) > code(0)
    expectedLabels: "api,tests,code",
  },
  {
    name: "documentation-only",
    fixture: "docs/intro.md\nREADME.md\n",
    expectedLabels: "documentation",
  },
  {
    name: "no-match",
    fixture: "Makefile\nLICENSE\n",
    expectedLabels: "",
  },
];

// Files/dirs to copy into each temp repo. node_modules is intentionally
// excluded — the workflow needs no third-party runtime deps.
const COPY_ITEMS = [
  "src",
  "fixtures",
  ".github",
  "package.json",
  "tsconfig.json",
  ".actrc",
];

/** Build an isolated temp git repo for one case; returns its path. */
function setupRepo(c: ActCase): string {
  const dir = mkdtempSync(join(tmpdir(), `act-label-${c.name}-`));
  for (const item of COPY_ITEMS) {
    cpSync(join(PROJECT_ROOT, item), join(dir, item), { recursive: true });
  }
  // Overwrite the fixture with this case's changed-file list.
  writeFileSync(join(dir, "fixtures/changed-files.txt"), c.fixture);

  // act needs a real git repo with at least one commit.
  const git = (args: string[]) =>
    spawnSync("git", args, { cwd: dir, encoding: "utf8" });
  git(["init", "-q", "-b", "main"]);
  git(["config", "user.email", "harness@example.com"]);
  git(["config", "user.name", "act harness"]);
  git(["add", "-A"]);
  git(["commit", "-q", "-m", "fixture commit"]);
  return dir;
}

/** Strip ANSI color/escape codes that act may emit so exact matches are reliable. */
function stripAnsi(s: string): string {
  return s.replace(/\x1b\[[0-9;]*m/g, "");
}

/** Extract the LABELS= value from act output, stripping act's log prefixes. */
function extractLabels(output: string): string | null {
  // Lines look like: "[PR Label Assigner/...] | LABELS=api,tests,code"
  const clean = stripAnsi(output);
  const matches = [...clean.matchAll(/LABELS=([^\r\n]*)/g)];
  if (matches.length === 0) return null;
  // Take the last occurrence and trim trailing whitespace.
  return matches[matches.length - 1]![1]!.replace(/\s+$/, "");
}

function delimiter(title: string): string {
  const bar = "=".repeat(72);
  return `\n${bar}\n${title}\n${bar}\n`;
}

let failures = 0;

// Start a fresh result file.
writeFileSync(
  RESULT_FILE,
  `act integration results for pr-label-assigner.yml\nGenerated by run-act-tests.ts\n`,
);

for (const c of CASES) {
  console.log(`\n>>> Running act case: ${c.name}`);
  const dir = setupRepo(c);
  try {
    const result = spawnSync(
      "act",
      // --pull=false: the act-ubuntu-pwsh image is a LOCAL image; without this
      // act force-pulls from a registry and fails with an auth error.
      ["push", "--rm", "--pull=false", "-P", "ubuntu-latest=act-ubuntu-pwsh:latest"],
      { cwd: dir, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
    );
    const output = `${result.stdout ?? ""}\n${result.stderr ?? ""}`;
    const exitCode = result.status ?? -1;

    appendFileSync(
      RESULT_FILE,
      delimiter(`CASE: ${c.name} | fixture=${JSON.stringify(c.fixture)} | expected LABELS=${c.expectedLabels}`) +
        output +
        `\n[harness] act exit code: ${exitCode}\n`,
    );

    // --- Assertions ---
    const errors: string[] = [];
    if (exitCode !== 0) errors.push(`act exit code ${exitCode} (expected 0)`);
    if (!/Job succeeded/.test(output)) errors.push("missing 'Job succeeded'");

    const labels = extractLabels(output);
    if (labels === null) {
      errors.push("no LABELS= line found in output");
    } else if (labels !== c.expectedLabels) {
      errors.push(
        `LABELS mismatch: got "${labels}", expected "${c.expectedLabels}"`,
      );
    }

    if (errors.length > 0) {
      failures++;
      console.error(`  FAIL [${c.name}]:`);
      for (const e of errors) console.error(`    - ${e}`);
      appendFileSync(
        RESULT_FILE,
        `[harness] RESULT: FAIL — ${errors.join("; ")}\n`,
      );
    } else {
      console.log(
        `  PASS [${c.name}]: LABELS="${labels}", Job succeeded, exit 0`,
      );
      appendFileSync(RESULT_FILE, `[harness] RESULT: PASS\n`);
    }
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const summary = `\n${"#".repeat(72)}\nSUMMARY: ${CASES.length - failures}/${CASES.length} cases passed\n${"#".repeat(72)}\n`;
appendFileSync(RESULT_FILE, summary);
console.log(summary.trim());
console.log(`Full output written to: ${RESULT_FILE}`);

process.exit(failures === 0 ? 0 : 1);
