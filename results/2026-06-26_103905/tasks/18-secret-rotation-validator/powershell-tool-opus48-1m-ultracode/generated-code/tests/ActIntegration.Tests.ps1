#requires -Modules @{ ModuleName = 'Pester'; ModuleVersion = '5.0.0' }

<#
.SYNOPSIS
    End-to-end integration tests that drive the workflow through `act`.

.DESCRIPTION
    Per the task requirements, every functional test case is exercised by running
    the real GitHub Actions workflow inside Docker via nektos/act. For each test
    case this harness:
      1. Builds an isolated temp git repo containing the project files plus that
         case's fixture data (copied to the configured secrets.json).
      2. Runs `act push --rm` and captures the full output + exit code.
      3. Appends the output to act-result.txt (clearly delimited) in the repo root.
      4. Asserts act exited 0, every job reports "Job succeeded", and the workflow
         emitted the EXACT expected rotation summary + per-secret lines.

    These tests are tagged 'Act' / 'Integration' so they can be excluded for fast
    local runs:  Invoke-Pester -ExcludeTagFilter Act

    NOTE: each test case is one `act push`. Running this file runs act 3 times.
#>

BeforeDiscovery {
    # The case matrix is needed at DISCOVERY time so -ForEach can expand it.
    # Expected values are the known-good outputs computed from each fixture
    # (verified independently against the module's unit tests).
    $script:Cases = @(
        @{
            Name            = 'case1-mixed'
            Fixture         = 'case1-mixed.json'
            ExpectedSummary = 'ROTATION-SUMMARY expired=1 warning=1 ok=1 total=3'
            ExpectedLines   = @(
                'SECRET name=db-password status=Expired daysSinceRotation=178 daysUntilExpiry=-88 requiredBy=api,worker'
                'SECRET name=api-token status=Warning daysSinceRotation=88 daysUntilExpiry=2 requiredBy=gateway'
                'SECRET name=tls-cert status=Ok daysSinceRotation=27 daysUntilExpiry=338 requiredBy=web'
            )
        },
        @{
            Name            = 'case2-all-ok'
            Fixture         = 'case2-all-ok.json'
            ExpectedSummary = 'ROTATION-SUMMARY expired=0 warning=0 ok=2 total=2'
            ExpectedLines   = @(
                'SECRET name=signing-key status=Ok daysSinceRotation=3 daysUntilExpiry=27 requiredBy=release,ci'
                'SECRET name=service-account status=Ok daysSinceRotation=8 daysUntilExpiry=82 requiredBy=scheduler'
            )
        },
        @{
            Name            = 'case3-mostly-expired'
            Fixture         = 'case3-mostly-expired.json'
            ExpectedSummary = 'ROTATION-SUMMARY expired=2 warning=0 ok=1 total=3'
            ExpectedLines   = @(
                'SECRET name=legacy-key status=Expired daysSinceRotation=543 daysUntilExpiry=-453 requiredBy=billing'
                'SECRET name=ssh-deploy-key status=Expired daysSinceRotation=58 daysUntilExpiry=-28 requiredBy=deployer'
                'SECRET name=monitoring-token status=Ok daysSinceRotation=0 daysUntilExpiry=90 requiredBy=observability'
            )
        }
    )
}

BeforeAll {
    $script:RepoRoot      = Split-Path -Parent $PSScriptRoot
    $script:ActResultPath = Join-Path $RepoRoot 'act-result.txt'

    # Resolve the act binary (PATH, then the common ~/.local/bin location).
    $script:ActBin = (Get-Command act -ErrorAction SilentlyContinue)?.Source
    if (-not $ActBin) {
        $fallback = Join-Path $HOME '.local/bin/act'
        if (Test-Path $fallback) { $script:ActBin = $fallback }
    }
    if (-not $ActBin) { throw "act binary not found on PATH or in ~/.local/bin." }

    # Custom image pre-loaded with pwsh + Pester (mapped via the workspace .actrc).
    $script:ActImage = 'act-ubuntu-pwsh:latest'

    # Files every isolated test repo needs to run BOTH workflow jobs.
    $script:ProjectFiles = @(
        'SecretRotationValidator.psm1'
        'secret-rotation-validator.ps1'
        '.actrc'
    )

    # (Re)initialise the aggregate act log artifact.
    $header = @(
        "Secret Rotation Validator - act integration results"
        "Generated by tests/ActIntegration.Tests.ps1"
        ("Cases: " + (($Cases | ForEach-Object { $_.Name }) -join ', '))
    ) -join [Environment]::NewLine
    Set-Content -LiteralPath $ActResultPath -Value $header -Encoding utf8

    # ---- Engine: build an isolated repo for a case and run the workflow ----
    function Invoke-ActForCase {
        param(
            [Parameter(Mandatory)] [string] $Name,
            [Parameter(Mandatory)] [string] $Fixture
        )

        $work = Join-Path ([System.IO.Path]::GetTempPath()) ("act-srv-" + [guid]::NewGuid().ToString('N'))
        $logFile = Join-Path ([System.IO.Path]::GetTempPath()) ("act-log-" + [guid]::NewGuid().ToString('N') + ".txt")
        New-Item -ItemType Directory -Path $work -Force | Out-Null

        try {
            # Copy the flat project files.
            foreach ($f in $ProjectFiles) {
                Copy-Item -LiteralPath (Join-Path $RepoRoot $f) -Destination (Join-Path $work $f) -Force
            }
            # Copy the workflow.
            $wfDir = Join-Path $work '.github/workflows'
            New-Item -ItemType Directory -Path $wfDir -Force | Out-Null
            Copy-Item -LiteralPath (Join-Path $RepoRoot '.github/workflows/secret-rotation-validator.yml') `
                -Destination (Join-Path $wfDir 'secret-rotation-validator.yml') -Force
            # Copy the fixtures dir (the in-CI unit tests read these).
            Copy-Item -LiteralPath (Join-Path $RepoRoot 'fixtures') -Destination (Join-Path $work 'fixtures') -Recurse -Force
            # Copy ONLY the unit-test file (the workflow's test job runs exactly this one;
            # the workflow/act suites need tools that aren't in the container).
            $testsDir = Join-Path $work 'tests'
            New-Item -ItemType Directory -Path $testsDir -Force | Out-Null
            Copy-Item -LiteralPath (Join-Path $RepoRoot 'tests/SecretRotationValidator.Tests.ps1') `
                -Destination (Join-Path $testsDir 'SecretRotationValidator.Tests.ps1') -Force

            # This case's fixture becomes the config the workflow validates.
            Copy-Item -LiteralPath (Join-Path $RepoRoot "fixtures/$Fixture") `
                -Destination (Join-Path $work 'secrets.json') -Force

            # A committed git repo is required for the `push` event.
            Push-Location $work
            try {
                & git init -q 2>&1 | Out-Null
                & git config user.email 'ci@example.com' 2>&1 | Out-Null
                & git config user.name 'CI Harness' 2>&1 | Out-Null
                & git add -A 2>&1 | Out-Null
                & git commit -q -m "fixture: $Name" 2>&1 | Out-Null

                # --pull=false: the custom image is local-only (no registry to pull
                # from). -P pins ubuntu-latest to it regardless of global .actrc.
                & $ActBin push --rm --pull=false -P "ubuntu-latest=$ActImage" *> $logFile
                $exit = $LASTEXITCODE
            }
            finally {
                Pop-Location
            }

            $output = if (Test-Path $logFile) { Get-Content -Raw -LiteralPath $logFile } else { '' }

            # Append this case's full output to the aggregate artifact.
            $delim = '=' * 80
            $block = @(
                ''
                $delim
                "ACT CASE: $Name   (fixture: $Fixture)"
                "act command: act push --rm --pull=false -P ubuntu-latest=$ActImage"
                "act exit code: $exit"
                $delim
                $output
            ) -join [Environment]::NewLine
            Add-Content -LiteralPath $ActResultPath -Value $block -Encoding utf8

            return [pscustomobject]@{
                Name     = $Name
                ExitCode = $exit
                Output   = $output
                Tail     = (($output -split "`r?`n" | Select-Object -Last 30) -join [Environment]::NewLine)
            }
        }
        finally {
            if (Test-Path $work)    { Remove-Item -Recurse -Force $work    -ErrorAction SilentlyContinue }
            if (Test-Path $logFile) { Remove-Item -Force          $logFile -ErrorAction SilentlyContinue }
        }
    }

    # Run every case once (each is one `act push`) and cache the results so the
    # per-case It blocks below can assert without re-running act.
    $script:Results = @{}
    foreach ($case in $Cases) {
        # Progress visibility for the slow act runs (Write-Information avoids the
        # PSAvoidUsingWriteHost analyzer warning while still printing to the host).
        Write-Information "[act] running workflow for $($case.Name) ..." -InformationAction Continue
        $script:Results[$case.Name] = Invoke-ActForCase -Name $case.Name -Fixture $case.Fixture
    }
}

Describe 'Workflow via act: <Name>' -Tag 'Act', 'Integration' -ForEach $Cases {

    It 'act exits with code 0' {
        $result = $script:Results[$Name]
        $result.ExitCode | Should -Be 0 -Because "act output tail:`n$($result.Tail)"
    }

    It 'every job reports "Job succeeded" (and none failed)' {
        $result = $script:Results[$Name]
        $succeeded = ([regex]::Matches($result.Output, 'Job succeeded')).Count
        $succeeded | Should -BeGreaterOrEqual 2 -Because "expected both the test and report jobs to succeed"
        $result.Output | Should -Not -Match 'Job failed'
    }

    It 'runs the Pester unit tests inside the pipeline' {
        $result = $script:Results[$Name]
        $result.Output | Should -Match 'unit tests passed'
    }

    It 'emits the exact rotation summary line' {
        $result = $script:Results[$Name]
        $result.Output | Should -Match ([regex]::Escape($ExpectedSummary))
    }

    It 'produces both the Markdown and JSON report formats' {
        $result = $script:Results[$Name]
        $result.Output | Should -Match '# Secret Rotation Report'   # Markdown
        $result.Output | Should -Match '"referenceDate":'           # JSON
    }

    It 'emits the exact per-secret line: <_>' -ForEach $ExpectedLines {
        $line = $_
        $result = $script:Results[$Name]
        $result.Output | Should -Match ([regex]::Escape($line))
    }
}
