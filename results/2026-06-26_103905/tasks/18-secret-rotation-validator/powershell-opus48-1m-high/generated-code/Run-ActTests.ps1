#!/usr/bin/env pwsh
#
# Run-ActTests.ps1
#
# End-to-end test harness that exercises the Secret Rotation Validator entirely
# through the GitHub Actions workflow using nektos/act. For each test case it:
#
#   1. Builds a throwaway temp git repo containing the project files plus that
#      case's fixture data (written to fixtures/secrets.json).
#   2. Runs `act push --rm` and captures the combined output.
#   3. Appends the captured output to act-result.txt (delimited per case).
#   4. Asserts act exited 0, that every job reports "Job succeeded", and that
#      the workflow output matches the EXACT expected values for that fixture.
#
# Run from the project directory:  pwsh -File ./Run-ActTests.ps1
# Exit code is 0 only when every case passes every assertion.
#
[CmdletBinding()]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$projectDir = $PSScriptRoot
$resultFile = Join-Path $projectDir 'act-result.txt'

# Start each run with a fresh result artifact.
"Secret Rotation Validator - act end-to-end results" | Set-Content -Path $resultFile
"Generated by Run-ActTests.ps1" | Add-Content -Path $resultFile
("=" * 72) | Add-Content -Path $resultFile

# Files/dirs copied into every temp repo. The workflow pins REFERENCE_DATE to
# 2026-06-27, so all expected values below are computed against that date with
# the default 14-day warning window.
$copyItems = @(
    'SecretRotationValidator.psm1',
    'SecretRotationValidator.Tests.ps1',
    'Invoke-Validator.ps1',
    '.github',
    '.actrc'
)

# ---------------------------------------------------------------------------
# Test cases: fixture content + EXACT expected workflow output.
# ---------------------------------------------------------------------------
$cases = @(
    @{
        name    = 'mixed-urgency'
        fixture = @'
{
  "secrets": [
    {"name":"expired-db","lastRotated":"2026-01-01","policyDays":30,"requiredBy":["api"]},
    {"name":"expired-stripe","lastRotated":"2026-02-01","policyDays":30,"requiredBy":["billing"]},
    {"name":"warn-tls","lastRotated":"2026-06-01","policyDays":30,"requiredBy":["ingress"]},
    {"name":"ok-jwt","lastRotated":"2026-06-01","policyDays":180,"requiredBy":["auth"]}
  ]
}
'@
        expectedSummary = 'Summary: Expired: 2 | Warning: 1 | OK: 1 | Total: 4'
        expectedGate    = 'ROTATION_GATE=FAILED'
        # The JSON report step must surface these exact secret names/urgencies.
        expectedContains = @('expired-db', 'expired-stripe', 'warn-tls', 'ok-jwt')
    },
    @{
        name    = 'all-ok'
        fixture = @'
{
  "secrets": [
    {"name":"fresh-key","lastRotated":"2026-06-20","policyDays":90,"requiredBy":["a"]},
    {"name":"long-lived","lastRotated":"2026-06-01","policyDays":180,"requiredBy":["b"]}
  ]
}
'@
        expectedSummary = 'Summary: Expired: 0 | Warning: 0 | OK: 2 | Total: 2'
        expectedGate    = 'ROTATION_GATE=PASSED'
        expectedContains = @('fresh-key', 'long-lived')
    },
    @{
        name    = 'warning-only'
        fixture = @'
{
  "secrets": [
    {"name":"w1","lastRotated":"2026-06-20","policyDays":10,"requiredBy":["a"]},
    {"name":"w2","lastRotated":"2026-06-15","policyDays":20,"requiredBy":["b"]},
    {"name":"w3","lastRotated":"2026-06-13","policyDays":14,"requiredBy":["c"]}
  ]
}
'@
        expectedSummary = 'Summary: Expired: 0 | Warning: 3 | OK: 0 | Total: 3'
        expectedGate    = 'ROTATION_GATE=PASSED'
        expectedContains = @('w1', 'w2', 'w3')
    }
)

# Collect per-assertion results; the harness fails if ANY assertion fails.
$failures = [System.Collections.Generic.List[string]]::new()

function Assert-Condition {
    param([bool] $Condition, [string] $Message)
    if ($Condition) {
        Write-Host "  [PASS] $Message" -ForegroundColor Green
    }
    else {
        Write-Host "  [FAIL] $Message" -ForegroundColor Red
        $script:failures.Add($Message)
    }
}

foreach ($case in $cases) {
    Write-Host "`n=== Running act case: $($case.name) ===" -ForegroundColor Cyan

    # --- Build the throwaway repo ------------------------------------------
    $tmp = Join-Path ([System.IO.Path]::GetTempPath()) ("srv-act-" + [guid]::NewGuid())
    New-Item -ItemType Directory -Path $tmp | Out-Null
    try {
        foreach ($item in $copyItems) {
            $src = Join-Path $projectDir $item
            Copy-Item -Path $src -Destination $tmp -Recurse -Force
        }
        # Write this case's fixture as the default config the workflow reads.
        $fixDir = Join-Path $tmp 'fixtures'
        New-Item -ItemType Directory -Path $fixDir -Force | Out-Null
        $case.fixture | Set-Content -Path (Join-Path $fixDir 'secrets.json')

        # act needs a git repo (actions/checkout operates on the committed tree).
        Push-Location $tmp
        try {
            git init -q
            git config user.email 'harness@example.com'
            git config user.name  'act harness'
            git add -A
            git commit -q -m "fixture: $($case.name)"

            # --- Run the pipeline through act ------------------------------
            # --pull=false: the act image is a local custom build, not in a registry.
            Write-Host "  running: act push --rm --pull=false" -ForegroundColor DarkGray
            $rawOutput = & act push --rm --pull=false 2>&1 | Out-String
            $actExit = $LASTEXITCODE
            # Strip ANSI colour codes so substring/regex assertions are robust
            # (Pester and act both colourise their output).
            $actOutput = $rawOutput -replace '\x1b\[[0-9;]*m', ''
        }
        finally {
            Pop-Location
        }

        # --- Persist output to the required artifact -----------------------
        $delim = "=" * 72
        Add-Content -Path $resultFile -Value "`n$delim"
        Add-Content -Path $resultFile -Value "TEST CASE: $($case.name)"
        Add-Content -Path $resultFile -Value "act exit code: $actExit"
        Add-Content -Path $resultFile -Value "Expected summary: $($case.expectedSummary)"
        Add-Content -Path $resultFile -Value "Expected gate:    $($case.expectedGate)"
        Add-Content -Path $resultFile -Value $delim
        Add-Content -Path $resultFile -Value $actOutput

        # --- Assertions ----------------------------------------------------
        Assert-Condition ($actExit -eq 0) "[$($case.name)] act exited 0 (got $actExit)"

        # Every job must report success and none may fail.
        $succeeded = ([regex]::Matches($actOutput, 'Job succeeded')).Count
        Assert-Condition ($succeeded -ge 2) "[$($case.name)] both jobs report 'Job succeeded' (found $succeeded)"
        Assert-Condition ($actOutput -notmatch 'Job failed') "[$($case.name)] no job reported 'Job failed'"

        # Exact expected values from the workflow output.
        Assert-Condition ($actOutput.Contains($case.expectedSummary)) `
            "[$($case.name)] summary line matches exactly: '$($case.expectedSummary)'"
        Assert-Condition ($actOutput.Contains($case.expectedGate)) `
            "[$($case.name)] rotation gate matches exactly: '$($case.expectedGate)'"

        # The Pester unit-test job must pass inside the pipeline too.
        Assert-Condition ($actOutput -match 'Tests Passed: \d+, Failed: 0') `
            "[$($case.name)] Pester suite passed inside the pipeline (Failed: 0)"

        foreach ($needle in $case.expectedContains) {
            Assert-Condition ($actOutput.Contains($needle)) `
                "[$($case.name)] report contains secret '$needle'"
        }
    }
    finally {
        if (Test-Path $tmp) { Remove-Item $tmp -Recurse -Force -ErrorAction SilentlyContinue }
    }
}

# ---------------------------------------------------------------------------
# Summary
# ---------------------------------------------------------------------------
Write-Host "`n$("=" * 50)" -ForegroundColor Cyan
if ($failures.Count -eq 0) {
    Write-Host "ALL ACT TESTS PASSED" -ForegroundColor Green
    Add-Content -Path $resultFile -Value "`n$("=" * 72)`nRESULT: ALL ACT TESTS PASSED"
    exit 0
}
else {
    Write-Host "ACT TESTS FAILED ($($failures.Count) assertion(s)):" -ForegroundColor Red
    $failures | ForEach-Object { Write-Host "  - $_" -ForegroundColor Red }
    Add-Content -Path $resultFile -Value "`n$("=" * 72)`nRESULT: FAILED ($($failures.Count) assertion(s))"
    exit 1
}
