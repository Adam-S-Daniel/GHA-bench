<#
.SYNOPSIS
    End-to-end test harness: runs every test case through the GitHub Actions
    workflow via `act` and asserts on exact expected label sets.
.DESCRIPTION
    For each case:
      1. Copies the project into a fresh temp git repo.
      2. Writes that case's mocked changed-file list as fixtures/changed-files.txt.
      3. Runs `act push --rm`, appending all output to act-result.txt.
      4. Asserts: act exit code 0, the exact expected `LABELS:` line, and
         that every job reports "Job succeeded".
    Exits non-zero if any assertion fails.
#>
[CmdletBinding()]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$repoRoot   = $PSScriptRoot
$resultFile = Join-Path $repoRoot 'act-result.txt'
Set-Content -Path $resultFile -Value "PR Label Assigner - act end-to-end results`nGenerated by Run-ActTests.ps1`n"

# Test cases: mocked PR changed-file lists and the exact label set the
# pipeline must print for each. Case 2 exercises priority/exclusive conflict
# resolution (docs/internal/** shadows docs/** for the same file).
$cases = @(
    [pscustomobject]@{
        Name         = 'case1-multi-rule-mapping'
        ChangedFiles = @('docs/readme.md', 'src/api/users.ps1', 'src/core/util.test.ts')
        Expected     = 'LABELS: api,documentation,tests'
    },
    [pscustomobject]@{
        Name         = 'case2-priority-conflict'
        ChangedFiles = @('docs/internal/secrets.md', 'docs/public.md', 'Makefile')
        Expected     = 'LABELS: documentation,internal-docs'
    }
)

$failures = [System.Collections.Generic.List[string]]::new()

foreach ($case in $cases) {
    Write-Host "=== Running $($case.Name) through act ===" -ForegroundColor Cyan

    # 1. Fresh temp repo with the project files + this case's fixture.
    $work = Join-Path ([IO.Path]::GetTempPath()) "act-$($case.Name)-$([Guid]::NewGuid().ToString('n').Substring(0,8))"
    New-Item -ItemType Directory -Path $work | Out-Null
    foreach ($item in @('LabelAssigner.psm1', 'Invoke-LabelAssigner.ps1', 'tests', 'fixtures', '.github', '.actrc')) {
        Copy-Item -Path (Join-Path $repoRoot $item) -Destination $work -Recurse
    }
    Set-Content -Path (Join-Path $work 'fixtures/changed-files.txt') -Value ($case.ChangedFiles -join "`n")

    git -C $work init -q
    git -C $work -c user.email=test@example.com -c user.name=test add -A
    git -C $work -c user.email=test@example.com -c user.name=test commit -qm "fixture for $($case.Name)"

    # 2. Run the workflow via act, capturing everything.
    Push-Location $work
    try {
        # --pull=false: the runner image act-ubuntu-pwsh:latest is local-only;
        # letting act force-pull it fails with a registry auth error.
        $output = & act push --rm --pull=false 2>&1 | ForEach-Object { "$_" }
        $exit = $LASTEXITCODE
    }
    finally {
        Pop-Location
    }

    # 3. Append delimited output to the required artifact.
    Add-Content -Path $resultFile -Value @(
        "==================== BEGIN $($case.Name) ===================="
        "Changed files: $($case.ChangedFiles -join ', ')"
        "Expected: $($case.Expected)"
        ""
        $output
        ""
        "act exit code: $exit"
        "==================== END $($case.Name) ======================"
        ""
    )

    # 4. Assertions on exact expected values.
    $text = $output -join "`n"
    if ($exit -ne 0) {
        $failures.Add("$($case.Name): act exited with code $exit (expected 0)")
    }
    if ($text -notmatch [regex]::Escape($case.Expected)) {
        $failures.Add("$($case.Name): output does not contain exact line '$($case.Expected)'")
    }
    $succeededJobs = @($output | Where-Object { $_ -match 'Job succeeded' })
    if ($succeededJobs.Count -lt 2) {
        $failures.Add("$($case.Name): expected both jobs (test, assign-labels) to report 'Job succeeded'; saw $($succeededJobs.Count)")
    }
    if ($text -match 'Job failed') {
        $failures.Add("$($case.Name): at least one job reported 'Job failed'")
    }

    Remove-Item -Recurse -Force $work
    Write-Host "--- $($case.Name): exit=$exit, succeeded-jobs=$($succeededJobs.Count) ---"
}

# Summary
Add-Content -Path $resultFile -Value "SUMMARY: $($cases.Count - ($failures | Group-Object { ($_ -split ':')[0] } | Measure-Object).Count)/$($cases.Count) cases passed"
if ($failures.Count) {
    Add-Content -Path $resultFile -Value ($failures | ForEach-Object { "FAIL: $_" })
    Write-Error ("act end-to-end tests FAILED:`n" + ($failures -join "`n"))
    exit 1
}
Add-Content -Path $resultFile -Value 'ALL ACT TESTS PASSED'
Write-Host 'ALL ACT TESTS PASSED' -ForegroundColor Green
