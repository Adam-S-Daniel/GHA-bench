// End-to-end pipeline verification: for each mock commit-log fixture, spins
// up an isolated temp git repo containing a copy of this project with that
// fixture's package.json/commits.log overlaid, runs the real
// .github/workflows/semantic-version-bumper.yml workflow via `act push`,
// and asserts the *exact* resulting version/bump-type values from the
// captured output — never by calling bump-version.ts directly. All act
// output is appended to act-result.txt in the repo root, clearly delimited
// per test case, as a required artifact.
import { describe, expect, test } from "bun:test";
import { cp, mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

const PROJECT_ROOT = join(import.meta.dir, "..", "..");
const ACT_RESULT_PATH = join(PROJECT_ROOT, "act-result.txt");

interface FixtureCase {
  fixture: string;
  previousVersion: string;
  bumpType: "major" | "minor" | "patch" | "none";
  newVersion: string;
}

// Two representative cases (feat→minor and breaking→major), chosen to stay
// within the project's "at most 3 act push invocations" budget while still
// exercising conventional-commit precedence end to end. fix→patch and the
// no-bump path are covered by tests/unit/fixtures.test.ts (same fixture
// files, exercised directly against runBump rather than through act).
const CASES: FixtureCase[] = [
  {
    fixture: "minor-feature",
    previousVersion: "1.1.0",
    bumpType: "minor",
    newVersion: "1.2.0",
  },
  {
    fixture: "major-breaking",
    previousVersion: "1.1.0",
    bumpType: "major",
    newVersion: "2.0.0",
  },
];

// Files/directories from the project root to copy into each temp repo.
// Excludes .git, node_modules, and act-result.txt itself.
const PROJECT_ENTRIES_TO_COPY = [
  ".github",
  "src",
  "tests",
  "fixtures",
  "bump-version.ts",
  "package.json",
  "tsconfig.json",
  "commits.log",
];

async function copyProjectInto(destDir: string): Promise<void> {
  for (const entry of PROJECT_ENTRIES_TO_COPY) {
    const src = join(PROJECT_ROOT, entry);
    await cp(src, join(destDir, entry), { recursive: true });
  }
}

async function run(
  cmd: string[],
  cwd: string,
): Promise<{ stdout: string; stderr: string; exitCode: number }> {
  const proc = Bun.spawn(cmd, { cwd, stdout: "pipe", stderr: "pipe" });
  const [stdout, stderr, exitCode] = await Promise.all([
    new Response(proc.stdout).text(),
    new Response(proc.stderr).text(),
    proc.exited,
  ]);
  return { stdout, stderr, exitCode };
}

async function appendActResult(heading: string, content: string): Promise<void> {
  const existing = (await Bun.file(ACT_RESULT_PATH).exists())
    ? await Bun.file(ACT_RESULT_PATH).text()
    : "";
  const delimiter = "=".repeat(80);
  const block = `${delimiter}\n${heading}\n${delimiter}\n${content}\n`;
  await Bun.write(ACT_RESULT_PATH, existing + block);
}

describe("semantic-version-bumper workflow via act", () => {
  // Start with a clean act-result.txt for this test run.
  test("act-result.txt is (re)initialized", async () => {
    await Bun.write(
      ACT_RESULT_PATH,
      `Semantic Version Bumper — act push results\nGenerated by tests/meta/workflow-act.test.ts\n\n`,
    );
    expect(await Bun.file(ACT_RESULT_PATH).exists()).toBe(true);
  });

  for (const testCase of CASES) {
    test(`fixture "${testCase.fixture}": ${testCase.previousVersion} -> ${testCase.newVersion} (${testCase.bumpType})`, async () => {
      const repoDir = await mkdtemp(join(tmpdir(), `svb-act-${testCase.fixture}-`));
      try {
        await copyProjectInto(repoDir);

        // Overlay this case's fixture data over the default version file /
        // commit log, exactly as the workflow's default inputs.
        await cp(
          join(PROJECT_ROOT, "fixtures", testCase.fixture, "package.json"),
          join(repoDir, "package.json"),
        );
        await cp(
          join(PROJECT_ROOT, "fixtures", testCase.fixture, "commits.log"),
          join(repoDir, "commits.log"),
        );

        await run(["git", "init", "-q"], repoDir);
        await run(["git", "config", "user.email", "test@example.com"], repoDir);
        await run(["git", "config", "user.name", "Test Runner"], repoDir);
        await run(["git", "add", "-A"], repoDir);
        await run(["git", "commit", "-q", "-m", "test"], repoDir);

        const act = await run(
          [
            "act",
            "push",
            "--rm",
            "--pull=false",
            "--rebuild=false",
            "-P",
            "ubuntu-latest=act-ubuntu-pwsh:latest",
          ],
          repoDir,
        );

        const combinedOutput = `${act.stdout}\n${act.stderr}`;
        await appendActResult(
          `Fixture: ${testCase.fixture} | expected ${testCase.previousVersion} -> ${testCase.newVersion} (${testCase.bumpType}) | exit code: ${act.exitCode}`,
          combinedOutput,
        );

        // 1. act must exit 0.
        expect(act.exitCode).toBe(0);

        // 2. Every job must report success.
        const jobSuccessCount = (combinedOutput.match(/Job succeeded/g) ?? []).length;
        expect(jobSuccessCount).toBeGreaterThanOrEqual(2); // bump-version + report

        // 3. Exact expected values, not just "a version number".
        expect(combinedOutput).toContain(`Previous version: ${testCase.previousVersion}`);
        expect(combinedOutput).toContain(`Bump type: ${testCase.bumpType}`);
        expect(combinedOutput).toContain(`New version: ${testCase.newVersion}`);
        expect(combinedOutput).toContain(`Resolved new version: ${testCase.newVersion}`);
      } finally {
        await rm(repoDir, { recursive: true, force: true });
      }
    }, 300_000); // act push can take 30-90s+; allow generous headroom
  }
});
